/**
 * @brief 安全的可变参数格式化函数（缓冲区安全）
 *
 * @param outbuf 输出缓冲区（必须非空且足够大）
 * @param bufsize 输出缓冲区大小（字节数）
 * @param format 格式化字符串（遵循 printf 格式规范）
 * @param ... 可变参数列表（匹配格式化字符串）
 * @return int 格式化结果：
 *             >=0: 实际需要的字符数（不包括终止符）
 *             <0: 发生错误
 *
 * @note 此函数保证：
 *   1. 输出缓冲区始终以 null 结尾
 *   2. 不会发生缓冲区溢出
 *   3. 正确处理所有边界情况
 *   4. 跨平台兼容（Windows/Linux/macOS/MinGW/Cygwin）
 *
 * 行为说明：
 *   - 如果 outbuf == NULL || bufsize == 0: 返回 -1（无效参数）
 *   - 如果 bufsize == 1: 设置 outbuf[0] = '\0'，返回 0
 *   - 如果 format == NULL: 设置 outbuf[0] = '\0'，返回 0
 *   - 如果格式化失败: 设置 outbuf[0] = '\0'，返回 -1
 *   - 如果输出被截断: 确保缓冲区正确终止，返回实际需要的字符数
 *
 * 错误处理：
 *   - 返回负值表示错误
 *   - 截断时设置 errno = ENOBUFS（如果平台支持）
 *   - 使用断言帮助调试（NDEBUG 定义时自动禁用）
 *
 * 设计原理：
 *   1. 优先进行参数验证，确保基础安全
 *   2. 处理所有边界情况（零缓冲区、单字节缓冲区等）
 *   3. 调用系统 vsnprintf 并检查返回值
 *   4. 显式确保缓冲区终止，避免平台差异
 *   5. 设置 errno 帮助调用者诊断截断情况
 *
 * 与标准 vsnprintf 的区别：
 *   - 保证缓冲区始终以 null 结尾
 *   - 处理 format == NULL 的边界情况
 *   - 统一错误返回值为 -1
 *   - 设置 errno 标识截断
 *   - 更严格的参数验证
 *
 * 使用示例：
 *   char buf[32];
 *   int len = vsnprintf_chkd(buf, sizeof(buf), "Value: %d", 42);
 *   if (len < 0) {
 *       // 处理错误
 *   } else if ((size_t)len >= sizeof(buf)) {
 *       // 处理截断
 *   }
 */
int vsnprintf_chkd(char *outbuf, size_t bufsize, const char *format, ...)
{
    /* 参数验证：空指针或零缓冲区大小 */
    if (!outbuf || bufsize == 0) {
        /* 调试断言（NDEBUG 定义时自动禁用） */
        DEBUG_ASSERT(outbuf != NULL && bufsize > 0 && "Invalid buffer (NULL or zero size)");
        return -1;
    }

    /* 边界情况：缓冲区仅能容纳终止符 */
    if (bufsize == 1) {
        DEBUG_ASSERT(bufsize == 1 && "Buffer size is 1 (only null terminator fits)");
        *outbuf = '\0';  /* 强制设置为空字符串 */
        return 0;        /* 返回 0 个写入字符 */
    }

    /* 边界情况：空格式字符串 */
    if (format == NULL) {
        DEBUG_ASSERT(format != NULL && "Format string is NULL (treated as empty string)");
        outbuf[0] = '\0';  /* 输出空字符串 */
        return 0;          /* 返回 0 个写入字符 */
    }

    va_list args;
    va_start(args, format);

    /* 调用系统格式化函数 */
    int len = vsnprintf(outbuf, bufsize, format, args);

    va_end(args);

    /* 处理系统错误（格式化失败） */
    if (len < 0) {
        DEBUG_ASSERT(len >= 0 && "vsnprintf system call failed (negative return value)");
        outbuf[0] = '\0';  /* 确保终止 */
        return -1;         /* 返回统一错误码 */
    }

    /* 处理缓冲区截断（需要空间 > 可用空间） */
    if ((size_t)len >= bufsize) {
        /* 设置截断错误码（平台支持时） */
    #ifdef ENOBUFS
        errno = ENOBUFS;  /* 输出缓冲区不足 */
    #elif defined(ENOMEM)
        errno = ENOMEM;    /* 次优回退 */
    #endif

        DEBUG_ASSERT((size_t)len < bufsize && "Output truncated (formatted data exceeds buffer size)");
        outbuf[bufsize - 1] = '\0';  /* 强制终止缓冲区 */
        return len;                  /* 返回实际需要的字符数 */
    }

    /* 成功路径：显式设置终止符（防御性编程） */
    errno = 0;            /* 清除错误状态 */
    outbuf[len] = '\0';   /* 确保正确终止（处理异常实现） */
    return len;           /* 返回实际写入字符数 */
}

/**
 * @brief 释放动态分配的字符串指针数组及其元素
 *
 * 此函数安全释放一个字符串指针数组（`char**`）中的所有非空字符串元素，
 * 并将每个指针位置置为 NULL。数组容器本身不会被释放（由调用方管理）。
 *
 * - 空安全：接受 NULL 数组指针（静默返回）
 * - 安全处理数组中包含的 NULL 指针
 * - 逆序释放：从数组末尾向开头处理（优化缓存性能）
 * - 防御性编程：释放后立即置空指针（防双重释放）
 *
 * @param varr   字符串指针数组（char** 类型），可为 NULL
 * @param maxnum 数组的实际元素数量（非容量）
 *
 * @warning 重要限制：
 * - 必须传递准确的元素数量（maxnum）
 * - 不会释放数组容器本身（仅处理元素）
 * - 若数组实际元素 > maxnum 会导致内存泄漏
 * - 若数组实际元素 < maxnum 会访问非法内存
 */
void cstr_varray_free(char** varr, int maxnum)
{
    while (varr && maxnum-- > 0) {
        char* p = varr[maxnum];
        if (p) {
            varr[maxnum] = NULL;  // 防御性置空
            mem_free(p);          // 释放字符串内存
        }
    }
}

/**
 * @brief 将字符串的前 num 个字符转换为大写形式
 *
 * 此函数原地修改字符串，将指定数量的字符转换为大写形式。
 * 转换在遇到字符串结束符或达到指定数量时停止。
 *
 * @param s     要转换的字符串（原地修改），必须为有效字符串指针
 * @param num   要转换的最大字符数（实际转换数 = min(num, strlen(s))）
 *
 * @return 返回原始字符串指针（便于链式调用）
 *
 * @note 安全性：
 * - 若 num > 实际长度，转换在遇到 '\0' 时停止
 * - 若 num < 0，函数立即返回（无操作）
 * - 不分配新内存，直接修改原字符串
 *
 * @warning 注意：
 * - 传入 NULL 指针会导致未定义行为
 * - 不会验证字符串边界，调用方需确保内存安全
 */
char* cstr_toupper(char* s, int num)
{
    char* p = s;
    // 同时检查字符计数和字符串结束符
    while (num-- > 0 && *p) {
        *p = toupper((unsigned char)*p);  // 确保无符号转换避免符号扩展问题
        p++;
    }
    return s;
}

/**
 * @brief 将字符串的前 num 个字符转换为小写形式
 *
 * 此函数原地修改字符串，将指定数量的字符转换为小写形式。
 * 转换在遇到字符串结束符或达到指定数量时停止。
 *
 * @param s     要转换的字符串（原地修改），必须为有效字符串指针
 * @param num   要转换的最大字符数（实际转换数 = min(num, strlen(s))）
 *
 * @return 返回原始字符串指针（便于链式调用）
 *
 * @note 特性：
 * - 处理速度：O(n) 时间复杂度，n=min(num, strlen(s))
 * - 支持 Unicode：依赖当前区域设置的 tolower() 行为
 * - 线程安全：无静态变量，但依赖线程安全的 ctype.h 实现
 *
 * @warning 重要限制：
 * - 不检查缓冲区溢出，调用方需确保内存有效性
 * - 负数 num 值会被静默忽略
 */
char* cstr_tolower(char* s, int num)
{
    char* p = s;
    while (num-- > 0 && *p) {             // 同时检查字符计数和字符串结束符
        *p = tolower((unsigned char)*p);  // 强制无符号转换保证正确性
        p++;
    }
    return s;
}

/**
 * @brief 移除字符串中所有指定字符（原地修改）
 *
 * @param s 要处理的字符串（可修改缓冲区）
 * @param c 要移除的字符
 * @return char* 返回处理后的字符串指针
 *
 * @note 特性：
 * - 原地修改字符串，不分配新内存
 */
char * cstr_remove_chr(char* s, char c)
{
    char *f = s, *p = s;
    while (*p) {
        if (*p != c) {
            *f++ = *p;
        }
        ++p;
    }
    *f = 0;
    return s;
}

/**
 * @brief 高效移除字符串中多个指定字符（原地修改）
 *
 * @param str 要处理的字符串（可修改缓冲区）
 * @param chrs 要移除的字符集合
 * @param num 要移除的字符数量
 * @return char* 处理后的字符串指针
 */
char * cstr_remove_chrs(char * str, const char * chrs, int num)
{
    // 创建字符查找表
    unsigned char lookup[UB1MAX + 1] = {0};

    // 标记要移除的字符=1（从前往后）
    for (int i = 0; i < num; i++) {
        lookup[(unsigned char)chrs[i]] = 1;
    }

    char *dest = str;
    char *src = str;

    while (*src) {
        if (!lookup[(unsigned char)*src]) {
            *dest++ = *src;
        }
        src++;
    }
    *dest = '\0';
    return str;
}

/**
 * @brief 移除字符串左侧（开头）的指定字符
 *
 * 此函数通过移动字符串指针移除开头的连续指定字符。
 * 原始内存不被释放，但返回的指针可能指向原字符串的不同位置。
 *
 * @param str  待处理的字符串（指针可能被修改）
 * @param ch   要移除的字符
 *
 * @return 返回移除左侧字符后的新字符串起始位置
 *
 * @note 重要特性：
 * - 时间复杂度：O(n)（n=左侧连续ch的数量）
 * - 不修改字符串内容，仅调整起始指针
 * - 返回的指针可能指向原字符串中部
 *
 * @warning 使用注意事项：
 * - 返回的新指针必须用于后续访问（原str指针可能失效）
 * - 不会释放或修改原始内存，仅调整起始位置
 * - 对只读内存段调用将导致未定义行为
 */
char* cstr_Ltrim_chr(char* str, char ch)
{
    // 跳过开头的连续指定字符
    while (str && *str && *str == ch) {
        str++;
    }
    return str;  // 返回第一个非ch字符的位置
}

/**
 * @brief 移除字符串右侧（结尾）的指定字符并返回长度
 *
 * 此函数通过截断字符串移除结尾的连续指定字符，
 * 同时可选返回新字符串长度。
 *
 * @param str      待处理的字符串（原地修改）
 * @param ch       要移除的字符
 * @param outlen   可选参数，用于接收新字符串长度
 *
 * @return 返回原始字符串指针（内容已被修改）
 *
 * @note 算法细节：
 * 1. 从字符串末尾向前扫描，跳过连续的指定字符
 * 2. 在第一个非指定字符位置后添加结束符
 * 3. 计算并返回新长度（可选）
 *
 * @warning 重要限制：
 * - 必须确保 str 指向可写内存
 * - 若字符串全由ch组成，结果将为空字符串（长度=0）
 * - outlen 为 NULL 时不计算长度
 */
char* cstr_Rtrim_chr(char* str, char ch, int* outlen)
{
    if (!str || !*str) {
        // 处理空字符串或NULL指针情况
        if (outlen) *outlen = 0;
        return str;
    }

    // 从字符串末尾开始向前扫描
    char* end = str + strlen(str) - 1;

    // 跳过尾部连续的指定字符
    while (end >= str && *end == ch) {
        end--;
    }

    // 在最后一个非ch字符后添加结束符
    *(end + 1) = '\0';

    // 计算新长度
    if (outlen) {
        *outlen = (end >= str) ? (int)(end - str + 1) : 0;
    }

    return str;
}

/**
 * @brief 在字符串的指定长度范围内从左向右查找字符
 *
 * 此函数在字符串的前 `len` 个字节或遇到空终止符前（以先到者为准）查找指定字符，
 * 返回第一个匹配字符的指针。
 *
 * @param str  要搜索的字符串（可为NULL）
 * @param len  要搜索的最大长度（字节数）
 * @param c    要查找的字符
 *
 * @return 找到则返回指向字符的指针，否则返回NULL
 *
 * @note 搜索特性：
 * - 搜索范围：min(len, strlen(str))
 * - 空安全：接受NULL指针（立即返回NULL）
 * - 边界安全：严格限制在[str, str+len)范围内
 *
 * @warning 重要限制：
 * - 不支持多字节字符（按字节搜索）
 * - 长度参数为有符号整数（负值视为无效）
 *
 * @example
 * char str[] = "hello";
 * char *p = cstr_Lfind_chr(str, 3, 'l');  // 在"hel"中查找，返回第一个'l'的位置(&str[2])
 * char *q = cstr_Lfind_chr(str, 2, 'l');  // 在"he"中查找，返回NULL（未找到）
 */
char* cstr_Lfind_chr(char* str, int len, char c)
{
    // 参数有效性检查
    if (!str || len <= 0) {
        return NULL;
    }

    char* p = str;
    // 同时检查长度限制和字符串结束符
    while ((p - str) < len && *p) {
        if (*p == c) {
            return p;  // 找到匹配
        }
        p++;
    }
    return NULL;  // 未找到
}

/**
 * @brief 在字符串的指定长度范围内从右向左查找字符
 *
 * 此函数在字符串的后 `len` 个字节中反向查找指定字符，
 * 返回最后一个匹配字符的指针。
 *
 * @param str  要搜索的字符串（可为NULL）
 * @param len  要搜索的最大长度（字节数）
 * @param c    要查找的字符
 *
 * @return 找到则返回指向字符的指针，否则返回NULL
 *
 * @note 算法特性：
 * - 反向遍历：从 str[len-1] 开始向字符串开头搜索
 * - 不依赖空终止符：严格在指定长度范围内搜索
 * - 性能：O(n) 最坏情况
 *
 * @warning 关键风险：
 * - 若 len > 实际分配内存，可能导致越界访问
 * - 若 str 未以空字符结尾且 len 过大，可能访问非法内存
 *
 * @example
 * char str[] = "hello";
 * char *p = cstr_Rfind_chr(str, 5, 'l');  // 返回第二个'l'的位置(&str[3])
 * char *q = cstr_Rfind_chr(str, 3, 'l');  // 在"hel"中查找，返回第一个'l'的位置(&str[2])
 */
char* cstr_Rfind_chr(char* str, int len, char c)
{
    if (!str || len <= 0) { // 参数有效性检查
        return NULL;
    }
    char* p = str + len - 1;  // 指向最后一个有效字符
    while (len-- > 0) {  // 反向遍历指定长度
        if (*p == c) {
            return p;  // 找到匹配
        }
        p--;
    }
    return NULL;  // 未找到
}

/**
 * @brief 在字符串中查找多个字符中的任意一个（首次出现）
 *
 * 此函数在指定长度范围内搜索字符串，查找字符集中任意字符的首次出现位置。
 *
 * @param str   要搜索的字符串（可为NULL）
 * @param len   要搜索的最大长度（字节数）
 * @param chrs  要查找的字符集合（非字符串，无终止符）
 * @param nch   字符集合中的字符数量
 *
 * @return 找到则返回指向第一个匹配字符的指针，否则返回NULL
 *
 * @note 搜索特性：
 * - 搜索范围：min(len, strlen(str))
 * - 空安全：接受NULL指针（立即返回NULL）
 * - 字符集顺序无关：任意匹配字符都会返回
 *
 * @warning 重要限制：
 * 1. 性能问题：字符集较大时效率低（O(n*m)时间复杂度）
 * 2. 不支持多字节字符（按字节搜索）
 * 3. 若 nch > 实际字符集大小，可能导致越界访问
 *
 * @example
 * char str[] = "Hello_World";
 * const char delims[] = {' ', '_', '-'};
 * char *p = cstr_find_chrs(str, 20, delims, 3);  // 返回 '_' 的位置(&str[5])
 *
 * @remark 对于大字符集，建议使用位图法优化：
 */
char * cstr_find_chrs(char * str, int len, const char *chrs, int nch)
{
    if (! str || len <= 0) {
        return NULL;
    }
    int i;
    char *p = str;
    while ((int)(p - str) < len && *p) {
        for (i = 0; i < nch; i++) {
            if (chrs[i] == *p) {
                return p;
            }
        }
        p++;
    }
    return NULL; // 未找到
}

/**
 * @brief 移除字符串开头的空白字符
 * @param str 要处理的字符串
 * @return 移除空白后的新字符串起始位置
 * @note 空白字符包括:
 *    ' '   (0x20)	space (SPC) arcii=32
 *    '\t'	(0x09)	horizontal tab (TAB)
 *    '\n'	(0x0a)	newline (LF)
 *    '\v'	(0x0b)	vertical tab (VT)
 *    '\f'	(0x0c)	feed (FF)
 *    '\r'	(0x0d)	carriage return (CR)
 */
char * cstr_Ltrim_whitespace(char *str)
{
    char *p = str;
    while (p && isspace((int)*p)) {
        p++;
    }
    return p;
}

/**
 * @brief 移除字符串末尾的空白字符
 * @param str 要处理的字符串(原地修改)
 * @param len 字符串长度
 * @return 新字符串长度
 * @note 从尾部开始移除连续空白字符
 * @see cstr_Ltrim_whitespace
 */
int cstr_Rtrim_whitespace(char *str, int len)
{
    while (len-- > 0) {
        if (isspace((int)str[len])) {
            str[len] = 0;
        } else {
            break;
        }
    }
    return len + 1;
}

/**
 * @brief 移除字符串两端的空白字符
 * @param str 要处理的字符串
 * @return 移除空白后的新字符串起始位置
 * @see cstr_Ltrim_whitespace
 */
char * cstr_LRtrim_whitespace(char *str)
{
    char *p = cstr_Ltrim_whitespace(str);
    cstr_Rtrim_whitespace(p, cstr_length(p, -1));
    return p;
}

/**
 * @brief 计算非空白内容的边界
 * @param str 源字符串
 * @param start 输入起始位置，输出非空白起始位置
 * @param end 输入结束位置，输出非空白结束位置
 * @return 非空白内容长度
 * @note 不修改原字符串，仅计算边界
 * 原函数名 cstr_shrink_whitespace
 */
int cstr_non_whitespace_range(const char *str, int *start, int *end)
{
    int s = *start;
    int e = *end;
    for (; s < *end; s++) {
        if (! isspace((int)str[s])) {
            break;
        }
    }
    *start = s;
    for (; e >= *start; e--) {
        if (! isspace((int)str[e])) {
            break;
        }
    }
    *end = e;
    return (*end - *start + 1);
}

