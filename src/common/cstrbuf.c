/**
 * @brief 去除字符串中的转义序列
 *
 * 此函数将处理字符串中的转义序列（特别是反斜杠转义）：
 * 1. "\\\\" → "\\"（两个反斜杠变为一个）
 * 2. "\\&" → "&"（转义的字符变为普通字符）
 *
 * @param str 输入字符串
 * @param len 输入字符串长度
 * @param chr 需要反转义的特殊字符（如 '&'）
 * @param copybuf 输出的字符串缓冲区(输出长度不会超过输入长度，因此调用者保证缓冲区长度为len即可)
 * @return int 处理后的 copybuf 字符串长度(不保证 copybuf 结尾为 '\0')
 *
 * @note 函数不会修改输入字符串
 */
int cstr_unescape_chr(const char *str, int len, char chr, char *copybuf)
{
    int r = 0;      // 读指针位置
    int w = 0;      // 写指针位置
    int escape = 0; // 转义状态标志

    // 遍历输入字符串
    while (r < len) {
        if (!escape && str[r] == '\\') {
            // 遇到转义字符，设置转义状态
            escape = 1;
            r++;
            continue;
        }

        if (escape) {
            // 处理转义序列
            escape = 0;

            if (str[r] == '\\' || str[r] == chr) {
                // 处理特定转义序列：\\ 和 \&
                copybuf[w++] = str[r++];
            } else {
                // 非特殊转义序列，保留反斜杠和字符
                copybuf[w++] = '\\';
                copybuf[w++] = str[r++];
            }
        } else {
            // 普通字符直接复制
            copybuf[w++] = str[r++];
        }
    }

    // 处理末尾的转义字符（如以单个 \ 结束）
    if (escape) {
        copybuf[w++] = '\\';
    }

    return w; // 返回处理后的字符串长度
}

/**
 * @brief 在字符串中查找下一个由字符串分隔的子串（不支持转义处理）
 *
 * 此函数在给定字符串范围内查找下一个由指定分隔字符串分隔的子串。
 * 不支持转义处理，分隔字符串被视为普通字符序列。
 *
 * @param start 当前搜索的起始位置（包含）
 * @param end 字符串结束位置（不包含），若为NULL则搜索到字符串结尾('\0')
 * @param sepstr 分隔字符串（如"$$"）
 * @param sepslen 分隔字符串的长度
 * @param[out] next 输出当前子串的起始位置
 * @param[out] nextlen 输出当前子串的长度
 *
 * @return const char*
 *   - 返回剩余字符串的起始位置（下一个子串开始的位置）
 *   - 若已到达字符串末尾，返回NULL
 *
 * @note 调用者必须确保start参数指向有效内存，end指向start字符串末尾('\0')或为NULL
 * @note 函数不会修改原始字符串内容，不支持转义处理，分隔字符串被视为普通字符序列
 * @note 当返回NULL时，表示没有更多子串，但此时next可能包含最后一个子串
 * @note 分隔字符串必须有效，（sepslen == 0）时行为未定义
 *
 * @see cstr_split_chr_next
 */
const char * cstr_split_str_next(const char *start, const char *end, const char* sepstr, int sepslen,
    const char **next, int *nextlen)
{
    const char* endsep = sepstr + sepslen;

    const char *s = start;
    const char *p = s;

    int found_sepstr;
    *next = NULL;

    while (p) {
        if (p == end || *p == 0) {
            *next = s;
            *nextlen = (int)(p - s);
            return NULL; // 有值且完成搜索
        }

        // p 查找 sepstr
        found_sepstr = 1;

        const char *a = p;
        const char *ep = sepstr;
        while (a != end && ep != endsep) {
            if (*a++ != *ep++) {
                found_sepstr = 0;
                break;
            }
        }

        if (found_sepstr && ep == endsep) {
            *next = s;
            *nextlen = (int)(p - s);
            p += sepslen;
            return p; // 有值期待下一个搜索
        }

        p++;
    }

    // 无值且完成搜索
    return NULL;
}

/**
 * @brief 计算字符串中由指定分隔符分隔的子串数量并存储子串信息
 *
 * 此函数通过重复调用cstr_split_str_next函数，计算在指定字符串范围内
 * 由分隔字符串分隔的子串总数，并可将子串的起始位置和长度存储到数组中。
 *
 * @param start 字符串搜索的起始位置（包含）
 * @param end 字符串结束位置（不包含），若为NULL则搜索到字符串结尾('\0')
 * @param sepstr 分隔字符串（如"$$"）
 * @param sepslen 分隔字符串的长度
 * @param[out] subs 存储子串起始位置的数组，若为NULL则不存储
 * @param[out] sublens 存储子串长度的数组，若为NULL则不存储
 * @param maxsubs 最大可存储的子串数量，若为0则仅计数不存储。不可以为负数
 *
 * @return int
 *   - 返回字符串中包含的子串总数
 *   - 当maxsubs>0时，返回实际存储的子串数量（不超过maxsubs）
 *
 * @note 调用者需确保subs和sublens数组的大小不小于maxsubs
 * @note 当maxsubs为0时，仅计算子串总数，不修改subs和sublens
 * @note 分隔字符串必须有效，（sepslen == 0）时行为未定义
 *
 * @see cstr_split_str_next
 */
int cstr_split_str_num(const char *start, const char *end, const char* sepstr, int sepslen,
    const char *subs[], int sublens[], int maxsubs)
{
    int i = 0;

    const char *next;
    int nextlen;
    const char *str = start;
    do {
        str = cstr_split_str_next(str, end, sepstr, sepslen, &next, &nextlen);
        if (next) {
            if (maxsubs > 0) {
                if (i < maxsubs) {
                    // 存储子串信息
                    subs[i] = next;
                    sublens[i] = nextlen;
                } else {
                    // 存储空间已满，立即返回
                    return i;  // 返回当前已存储的子串数量
                }
            }
            i++; // 增加子串计数
        }
    } while(str);

    // maxsubs>0: 返回实际保存的子串数量
    // 否则返回全部子串数量，并且不保存的任何子串
    return i;
}

/**
 * @brief 比较两个字符串是否不相等（区分大小写）
 *
 * 此函数用于比较两个以'\0'结尾的字符串是否不相等，是字符串不等性的判断函数。
 * 当两个字符串完全相同时返回false，否则返回true。
 *
 * @param s1 第一个待比较的字符串
 * @param s2 第二个待比较的字符串
 *
 * @return int
 *   - 返回 0：两个字符串完全相同
 *   - 返回 1：两个字符串不相同
 *
 * @note 当两个指针指向同一内存地址时，判定为相等
 * @note 支持NULL指针比较，NULL与任何非NULL字符串均判定为不相等
 * @note 比较过程区分大小写（如'A'与'a'被视为不同）
 *
 * @see cstr_neq_len
 */
int cstr_neq(const char *s1, const char *s2)
{
    if (s1 == s2) {
        return 0;
    }
    if (s1 && s2) {
        const char *a = s1;
        const char *b = s2;
        while (*a && *b) {
            // a != A
            if (*a++ != *b++) {
                // s1 != s2
                return 1;
            }
        }
        if (!*a && !*b) {
            // s1 == s2
            return 0;
        }
    }
    // s1 != s2
    return 1;
}

/**
 * @brief 比较指定长度的两个字符串片段是否不相等（区分大小写）
 *
 * 此函数用于比较两个字符串的指定长度片段是否不相等，是指定长度的字符串
 * 不等性判断函数。当两个片段完全相同时返回false，否则返回true。
 *
 * @param s1 第一个待比较的字符串
 * @param len1 第一个字符串参与比较的长度
 * @param s2 第二个待比较的字符串
 * @param len2 第二个字符串参与比较的长度
 *
 * @return int
 *   - 返回 0：两个字符串片段完全相同
 *   - 返回 1：两个字符串片段不相同
 *
 * @note 首先比较长度，长度不同直接判定为不相等
 * @note 当两个指针指向同一内存地址时，判定为相等
 * @note 支持NULL指针比较，NULL与任何非NULL字符串均判定为不相等
 * @note 比较过程区分大小写（如'A'与'a'被视为不同）
 *
 * @see cstr_neq
 */
int cstr_neq_len(const char *s1, size_t l1, const char *s2, size_t l2)
{
    if (s1 == s2) {
        // s1 == s2
        return 0; // false
    }
    if (!s1) {
        // s1 (null) != s2 (non-null)
        return 1; // true
    }
    if (!s2) {
        // s1 (non-null) != s2 (null)
        return 1; // true
    }

    // s1, s2: both non-null

    if (cstr_invalid_size(l1)) {
        l1 = strlen(s1);
    }
    if (cstr_invalid_size(l2)) {
        l2 = strlen(s2);
    }

    if (l1 != l2) {
        // s1 != s2
        return 1; // true
    }

    // l1 == l2
    if (!l1) {
        // s1 == s2: both empty
        return 0; // false
    }

    const char *end = s1 + l1;
    while (s1 < end) {
        if (*s1++ != *s2++) {
            // s1 != s2
            return 1;
        }
    }

    // s1 == s2
    return 0; // false
}

/**
 * @brief 安全比较两个字符串。字符串长度长的大于短的。相同的情况下规则与 strncmp 兼容。
 *
 * 按指定长度比较两个字符串的大小关系，支持忽略大小写，同时处理 NULL 指针、空字符串等边界场景，
 *
 * @param s1 第一个待比较的字符串（可传入 NULL）
 * @param l1 第一个字符串的比较长度；若传入 (size_t)(-1)，则自动计算 s1 的实际长度（依赖 strlen）
 * @param s2 第二个待比较的字符串（可传入 NULL）
 * @param l2 第二个字符串的比较长度；若传入 (size_t)(-1)，则自动计算 s2 的实际长度（依赖 strlen）
 * @param caseignore 是否忽略大小写（非 0 表示忽略，0 表示区分大小写）
 *
 * @return int
 *   - 返回 1：s1 大于 s2
 *   - 返回 0：s1 等于 s2
 *   - 返回 -1：s1 小于 s2
 *
 * @note 1. NULL 字符串（s1/s2 为 NULL）小于任何非 NULL 或空字符串（""）
 * @note 2. 长度不同时，较短的字符串视为更小（如 "abc" < "abcd"）
 * @note 3. 两个 NULL 字符串判定为相等（返回 0）
 * @note 4. 当 l1/l2 为 (size_t)(-1) 时，需确保非 NULL 的 s1/s2 是以 '\0' 结尾的合法字符串（否则 strlen 会越界）
 */
int cstr_compare(const char *s1, size_t l1, const char *s2, size_t l2, int caseignore)
{
    if (s1 == s2) {
        // same pointer
        return 0;
    }
    if (!s1) {
        // s2 is non-NULL: s1 < s2
        return (-1);
    }
    if (!s2) {
        // s1 is non-NULL: s1 > s2
        return 1;
    }

    if (cstr_invalid_size(l1)) {
        l1 = strlen(s1);
    }
    if (cstr_invalid_size(l2)) {
        l2 = strlen(s2);
    }

    if (l1 > l2) {
        // s1 > s2
        return 1;
    }
    if (l1 < l2) {
        // s1 < s2
        return -1;
    }

    // l1 == l2
    if (!l1) {
        // s1, s2 are both empty
        return 0;
    }

    // here: (l1==l2) > 0

    const char *end = s1 + l1;

    if (! caseignore) {
        // caseignore=0: a != A
        while (s1 < end) {
            int p = *s1++;
            int q = *s2++;
            if (p > q) {
                return 1;
            } else if (p < q) {
                return -1;
            }
        }
        // s1 == s2
        return 0;
    }

    // caseignore!=0: a == A
    while (s1 < end) {
        int p = *s1++;
        int q = *s2++;

        if (p == q) {
            continue;
        }

        p = tolower((unsigned char) p);
        q = tolower((unsigned char) q);

        if (p > q) {
            return 1;
        } else if (p < q) {
            return -1;
        }
    }
    // s1 == s2
    return 0;
}

/**
 * @brief 判断字符串是否以指定前缀开头（区分大小写）
 *
 * 验证目标字符串的起始部分是否与指定前缀完全一致，支持手动指定长度或自动计算长度（通过无效长度标记触发）。
 * 匹配规则：前缀长度需小于等于目标字符串长度，且对应位置字符完全相同（区分大小写）。
 *
 * @param str 目标字符串（待判断是否包含前缀的字符串）
 * @param len 目标字符串的比较长度；若传入无效长度(-1)，计算实际长度
 * @param start 前缀字符串（用于匹配的起始片段）
 * @param startlen 前缀字符串的长度；若传入无效长度(-1)，计算实际长度
 *
 * @return int
 *   - 返回 1：目标字符串以指定前缀开头（匹配成功）
 *   - 返回 0：目标字符串不以指定前缀开头（匹配失败，含空指针、长度不满足、字符不匹配等场景）
 *
 * @note 忽略参数有效性检查，调用者需确保：
 *       1. 非 NULL 的 str/start 是合法 C 字符串（以 '\0' 结尾），否则自动计算长度时 `strlen` 行为未定义
 *
 * @note 当 str 与 start 指向同一内存地址时，直接判定为匹配（返回 1）
 * @note 比较过程区分大小写（如 'A' 与 'a' 视为不同字符）
 */
int cstr_startswith(const char *str, size_t len, const char *start, size_t startlen)
{
    if (str == start) {
        return 1;
    }
    if (!str || !start) {
        return 0;
    }
    if (cstr_invalid_size(len)) {
        len = strlen(str);
    }
    if (cstr_invalid_size(startlen)) {
        startlen = strlen(start);
    }
    if (startlen > len) {
        return 0;
    }

    // len >= startlen
    const char * end = start + startlen;
    const char *s = str;
    const char *p = start;
    while (p < end) {
        if (*p++ != *s++) {
            return 0;
        }
    }
    return 1;
}

/**
 * @brief 判断字符串是否以指定后缀结尾（区分大小写）
 *
 * 验证目标字符串的末尾部分是否与指定后缀完全一致，支持手动指定长度或自动计算长度（通过无效长度标记触发）。
 * 匹配规则：后缀长度需小于等于目标字符串长度，且后缀与目标字符串末尾对应长度的字符完全相同（区分大小写）。
 *
 * @param str 目标字符串（待判断是否包含后缀的字符串）
 * @param len 目标字符串的有效长度；若传入无效长度(-1) 则自动调用 `strlen(str)` 计算实际长度
 * @param end 后缀字符串（用于匹配的末尾片段，如示例中的 "aBBBB"）
 * @param endlen 后缀字符串的长度；若传入无效长度(-1) 则自动调用 `strlen(str)` 计算实际长度
 *
 * @return int
 *   - 返回 1：目标字符串以指定后缀结尾（匹配成功，如示例中 str="aaaaBBBB"、end="aBBBB" 时返回 1）
 *   - 返回 0：目标字符串不以指定后缀结尾（匹配失败，含空指针、后缀长度超限、字符不匹配等场景）
 *
 * @note 忽略参数有效性检查，调用者需确保：
 *       1. 非 NULL 的 str/end 是合法 C 字符串（以 '\0' 结尾），否则自动计算长度时 `strlen` 行为未定义
 *
 * @note 当 str 与 end 指向同一内存地址时，直接判定为匹配（返回 1）
 * @note 比较过程区分大小写（如 'B' 与 'b' 视为不同字符）
 * @note 若后缀长度为 0（空字符串），则默认匹配成功（返回 1，空字符串是任何字符串的后缀）
 */
int cstr_endswith(const char *str, size_t len, const char *end, size_t endlen)
{
    if (str == end) {
        return 1;
    }
    if (!str || !end) {
        return 0;
    }
    if (cstr_invalid_size(len)) {
        len = strlen(str);
    }
    if (cstr_invalid_size(endlen)) {
        endlen = strlen(end);
    }
    if (endlen > len) {
        return 0;
    }

    // len >= endlen
    const char *s = str + len - endlen;
    const char *p = end;
    const char *endp = end + endlen;
    while (p < endp) {
        if (*p++ != *s++) {
            return 0;
        }
    }
    return 1;
}

/**
 * @brief 在目标字符串中查找第一个子串（区分大小写，支持自动计算长度）
 *
 * 在目标字符串 `str` 的前 `len` 个字符中，查找第一个与子串 `child` 完全匹配的片段，
 * 支持手动指定长度或通过 `cstr_invalid_size` 标记自动计算长度（依赖 `strlen`）。
 *
 * @param str 目标字符串（待查找子串的母串，非 NULL）
 * @param len 目标字符串的有效长度；若为无效长度（符合 `cstr_invalid_size` 规则），自动调用 `strlen(str)` 计算
 * @param child 待查找的子串（非 NULL）
 * @param childlen 子串的长度；若为无效长度（符合 `cstr_invalid_size` 规则），自动调用 `strlen(child)` 计算
 *
 * @return const char*
 *   - 成功：返回子串在目标字符串中第一次出现的起始指针（指向 `str` 中匹配片段的首字符）
 *   - 失败：返回 NULL（子串未找到、子串长于母串或参数无效）
 *
 * @note 若 `str` 与 `child` 指向同一内存地址，直接返回 `str`（视为匹配）
 * @note 比较过程区分大小写（如 'A' 与 'a' 视为不同字符）
 * @note 忽略参数有效性检查，调用者需确保非 NULL 指针指向合法 C 字符串
 */
const char* cstr_findchild(const char * str, size_t len, const char * child, size_t childlen)
{
    if (!str || !child) {
        return NULL;
    }
    if (cstr_invalid_size(len)) {
        len = strlen(str);
    }
    if (cstr_invalid_size(childlen)) {
        childlen = strlen(child);
    }
    // len >= childlen
    if (!childlen) {
        // 空串是任何字符串的子串
        return str;
    }
    if (len < childlen) {
        return NULL;
    }
    if (str == child) {
        return str;
    }

    assert(len >= childlen && childlen > 0);

    const char * start = str;
    const char * end = str + len - childlen; // 有效搜索终点

    for (; start <= end; ++start) {
        if (*start == *child && (childlen == 1 || ! memcmp(start + 1, child + 1, childlen - 1))) {
            return start;
        }
    }

    // not found
    return NULL;
}

/**
 * @brief 在目标字符串中查找数组内第一个存在的子串（支持大小写忽略）
 *
 * 遍历字符串数组 `array`，检查每个元素是否为目标字符串 `str` 的子串，返回第一个匹配元素的索引，
 * 支持通过 `caseignore` 控制是否忽略大小写，自动计算子串长度。
 *
 * @param str 目标字符串（待查找子串的母串，非 NULL）
 * @param len 目标字符串的有效长度；若为无效长度（符合 `cstr_invalid_size` 规则），自动调用 `strlen(str)` 计算
 * @param array 子串数组（每个元素为待查找的子串，非 NULL，数组以有效元素填充，长度由 `arraylen` 控制）
 * @param arraylen 子串数组的元素个数（需 >= 0）
 * @param caseignore 是否忽略大小写（非 0 表示忽略，0 表示区分）
 *
 * @return int
 *   - 成功：返回数组中第一个为 `str` 子串的元素索引（>= 0）
 *   - 失败：返回 -1（数组中无任何元素是 `str` 的子串）
 *
 * @note 忽略参数有效性检查，调用者需确保数组元素指向合法 C 字符串
 */
int cstr_findfirst_array(const char *str, size_t len, const char *array[], int arraylen, int caseignore)
{
    if (cstr_invalid_size(len)) {
        len = strlen(str);
    }
    for (int i = 0; i < arraylen; i++) {
        if (! cstr_compare(str, len, array[i], CSTR_ERR_SIZE, caseignore)) {
            return i;
        }
    }
    // not found
    return -1;
}

/**
 * @brief 检查字符串是否全部由数字字符组成
 *
 * @param str 待检查的字符串指针
 * @param len 字符串长度（使用-1表示以NULL结尾的字符串）
 *
 * @return int 返回1表示全部为数字字符，0表示包含非数字字符或空字符串
 */
int cstr_isdigit(const char *str, size_t len)
{
    if (!str) {
        return 0;
    }
    if (cstr_invalid_size(len)) {
        len = strlen(str);
    }
    if (len == 0) {
        return 0;  // 空字符串处理
    }
    for (size_t i = 0; i < len; i++) {
        // 正确转换避免符号扩展问题
        if (!isdigit((unsigned char)str[i])) {
            return 0;
        }
    }
    return 1;
}

/**
 * @brief 从文件流中读取一行文本
 *
 * @param fp 输入文件流指针（必须已打开）
 * @param line 存储读取内容的缓冲区
 * @param maxlen 缓冲区最大容量（包括终止符）
 * @param ignore_whitespace 是否忽略空白字符标志（非0忽略，0保留）
 *
 * @return int 成功时返回读取字符数（不含终止符），
 *             文件结尾且未读到数据时返回-1，
 *             错误时返回负值（需用feof/ferror判断）
 *
 * @note 特性：
 * - 自动处理UTF-8 BOM头（仅在文件开头）
 * - 跳过回车符(\r)，以换行符(\n)作为行结束标志
 * - 支持可选空白字符过滤
 * - 确保缓冲区以null结尾
 * - 不处理行续接（反斜杠处理需确认设计意图）
 */
int cstr_readline(FILE *fp, char line[], size_t maxlen, int ignore_whitespace)
{
    int ch, len = 0;
    int bytes_read = 0;

    if (ftell(fp) == 0) {
        int bom[3] = {0};
        for (int i = 0; i < 3; i++) {
            bom[i] = fgetc(fp);
            if (bom[i] == EOF) {
                break;
            }
            bytes_read++;
        }

        if (bom[0] == 0xEF && bom[1] == 0xBB && bom[2] == 0xBF) {
            // 已跳过BOM，不需要：fseek(fp, 3, SEEK_SET);
        } else {
            // 回退非BOM字节：fseek(fp, 0, SEEK_SET);
            for (int i = bytes_read - 1; i >= 0; i--) {
                ungetc(bom[i], fp);
            }
        }
    }

    while ((ch = fgetc(fp)) != EOF) {
        if ((size_t) len < maxlen - 1) {
            if (ch != '\r' && ch != '\n' && ch != '\\') {
                if (! ignore_whitespace || ! isspace((unsigned char)ch)) {
                    line[len++] = ch;
                }
            }
        }

        if (ch == '\n') {
            break;
        }
    }

    if (ch == EOF && len == 0) {
        // end of file
        return -1;
    }

    line[len] = '\0';
    return len;
}

/**
 * @brief 将日期时间结构格式化为字符串
 *
 * @param dt 日期时间结构体指针
 * @param outfmt 输出缓冲区（长度至少为CSTR_DTFMT_SIZE_MAX）
 * @return const char* 格式化后的字符串指针（同outfmt）
 *
 * @note 格式化规则：
 * - 仅输出有效字段（值为-1表示无效）
 * - 日期格式：YYYY-MM-DD
 * - 时间格式：HH:MM:SS
 * - 毫秒格式：.SSS
 * - 时区格式：+HH:MM 或 WHH:MM（负时区）
 * - 字段间自动添加空格分隔
 * - 输出示例：
 *   "2023-01-15 14:30:45.500+08:00"
 *   "14:30:45-05:00"（仅时间+时区）
 *   "2023-01-15"（仅日期）
 */
const char * cstr_datetime_print(const cstr_datetime_t *dt, char outfmt[CSTR_DATE_BSIZE])
{
    size_t offset = 0;
    *outfmt = '\0'; // 确保空终止

    // 日期部分 (YYYY-MM-DD)
    if (dt->year != -1 && dt->month != -1 && dt->day != -1) {
        offset += vsnprintf_chkd(outfmt + offset,
                                  CSTR_DATE_BSIZE - offset,
                                  "%04d-%02d-%02d",
                                  dt->year, dt->month, dt->day);
    }

    // 时间部分 (HH:MM:SS)
    int has_time = 0;
    if (dt->hour != -1 && dt->minute != -1 && dt->second != -1) {
        if (offset > 0) {
            // 日期与时间间加空格
            outfmt[offset++] = ' ';
        }
        offset += vsnprintf_chkd(outfmt + offset,
                                   CSTR_DATE_BSIZE - offset,
                                   "%02d:%02d:%02d",
                                   dt->hour, dt->minute, dt->second);
        has_time = 1;
    }

    // 毫秒部分 (.SSS)
    if (has_time && dt->millisecond != -1) {
        offset += vsnprintf_chkd(outfmt + offset,
                                   CSTR_DATE_BSIZE - offset,
                                   ".%03d",
                                   dt->millisecond);
    }

    // 时区部分 (±HH:MM)
    if (dt->timezone != -1) {
        // 添加分隔符（如果前面有内容）
        if (offset > 0) {
            outfmt[offset++] = (dt->timezone >= 0) ? '+' : '-';
        }

        int tz_abs = abs(dt->timezone);
        offset += vsnprintf_chkd(outfmt + offset,
                                   CSTR_DATE_BSIZE - offset,
                                   "%02d:%02d",
                                   tz_abs / 100,
                                   tz_abs % 100);
    }

    return outfmt;
}

/**
 * @brief 验证日期时间各字段的有效性
 *
 * @param year  年份 (1900-9999)
 * @param mon   月份 (1-12)
 * @param day   日期 (1-31，实际根据月份验证)
 * @param hour  小时 (0-24)
 * @param min   分钟 (0-59)
 * @param sec   秒数 (0-60，60用于闰秒)
 *
 * @return int 1表示有效，0表示无效
 *
 * @note 特殊规则：
 * - 闰秒允许秒数为60（根据国际地球自转服务引入）
 * - 小时允许24:00表示一天结束（ISO 8601标准）
 * - 二月天数自动处理闰年规则
 * - 各字段有独立的有效性范围检查
 */
int time_is_valid(int year, int mon, int day, int hour, int min, int sec)
{
    /* 基础范围检查 */
    if (year < 1900 || year > 9999) return 0;
    if (mon < 1 || mon > 12) return 0;
    if (day < 1 || day > 31) return 0;
    if (hour < 0 || hour > 24) return 0;  // 允许24但禁止大于24

    /* 处理24:00:00特殊情况 */
    if (hour == 24) {
        // 24小时表示法要求分秒为0
        if (min != 0 || sec != 0) {
            return 0;
        }
        // 24:00:00是有效时间，直接验证日期部分
    } else {
        // 常规时间检查
        if (min < 0 || min >= 60) return 0;
        if (sec < 0 || sec >= 61) return 0;  // 包含闰秒60
    }

    /* 闰秒验证 (sec=60) */
    if (sec == 60) {
        // 闰秒必须发生在有效分钟内
        if (min < 0 || min >= 60) return 0;
    }

    /* 月份天数验证 - 现在只依赖日期部分 */
    if (mon == 1 || mon == 3 || mon == 5 || mon == 7 || mon == 8 || mon == 10 || mon == 12) {
        return 1;  // 31天月份有效
    } else if (mon == 4 || mon == 6 || mon == 9 || mon == 11) {
        return (day <= 30) ? 1 : 0;  // 30天月份
    } else {
        // 二月特殊处理
        if (day > 29) return 0;
        if (day < 29) return 1;

        /* 闰年判断 */
        return TM_YEAR_IS_LEAP(year);
    }
}

/**
 * @brief 解析时区字符串为整数表示
 *
 * @param tz 时区字符串指针（格式："+08:00"、"-05:30"、"E0800"、"W0830"等）
 *
 * @return int
 *   - 成功：返回时区偏移值（单位：百分之一小时）
 *       示例：+08:00 -> 800, -05:30 -> -530
 *   - 失败：返回-1
 *
 * @note 支持的格式：
 *   - 带分隔符："[+-][HH]:[MM]" 或 "[EW][HH]:[MM]"（分隔符可以是':'或'.'）
 *   - 无分隔符："[EW][HH][MM]"
 *   - 小时范围：00-23
 *   - 分钟范围：00-59
 */
int cstr_parse_timezone(char *tz)
{
    if (!tz || !*tz) return -1;

    int sign = 0;
    /* 解析符号部分 */
    if (*tz == '+' || *tz == 'E') {
        sign = 1;
    } else if (*tz == '-' || *tz == 'W') {
        sign = -1;
    } else {
        return -1;
    }

    int h = 0, m = 0;
    char *p = tz + 1;

    /* 格式1: 带分隔符（[+-EW]HH:MM） */
    if (isdigit((unsigned char)p[0]) &&
        isdigit((unsigned char)p[1]) &&
        (p[2] == ':' || p[2] == '.') &&
        isdigit((unsigned char)p[3]) &&
        isdigit((unsigned char)p[4]) &&
        p[5] == '\0')
    {
        h = (p[0] - '0') * 10 + (p[1] - '0');
        m = (p[3] - '0') * 10 + (p[4] - '0');
    }
    /* 格式2: 无分隔符（[EW]HHMM） */
    else if (isdigit((unsigned char)p[0]) &&
             isdigit((unsigned char)p[1]) &&
             isdigit((unsigned char)p[2]) &&
             isdigit((unsigned char)p[3]) &&
             p[4] == '\0')
    {
        h = (p[0] - '0') * 10 + (p[1] - '0');
        m = (p[2] - '0') * 10 + (p[3] - '0');
    }
    else {
        return -1; // 无效格式
    }

    /* 验证时间范围 */
    if (h < 0 || h > 23 || m < 0 || m > 59) {
        return -1;
    }

    return (h * 100 + m) * sign;
}

/**
 * @brief 解析时间戳字符串为时间结构和毫秒时间戳
 *
 * @param timestr 时间戳字符串（支持多种格式）
 * @param outdt 输出时间结构（可为NULL）
 * @return ub8 成功时返回UTC毫秒时间戳，失败返回(ub8)-1
 *
 * @note 支持格式：
 *   - 完整格式：'2019-12-22 12:36:59.065+08:00'
 *   - 无毫秒：'2019-12-22 12:36:59-08:00'
 *   - 无时间：'2019-12-22+08:00'
 *   - 带引号：'2019-12-22 12:36:59'
 *
 * @note 时区表示：
 *   - UTC+08:00 可表示为 +08:00, E0800
 *   - UTC-11:00 可表示为 -11:00, W1100
 */
ub8 cstr_parse_timestamp(char *timestr, cstr_datetime_t *outdt)
{
    int len = 0;
    int YMD = 0, HMS = 0, MMM = 0;

    /**
     * UTC+08:00 = +0800 or E0800
     * UTC-11:00 =        W0800
     *
     * '2019-12-22 12:36:59.065+08:00' or '2019-12-22 12:36:59.065E08:00'
     * '2019-12-22 12:36:59.065'
     * '2019-12-22 12:36:59W08:00' or '2019-12-22 12:36:59-08:00'
     * '2019-12-22 12:36:59'
     * '2019-12-22E08:00' or '2019-12-22+08:00'
     * '2019-12-22'
     */
    char Year[5] = {'0', '0', '0', '0', '\0'};
    char Mon[3] = {'0', '0', '\0'};
    char Day[3] = {'0', '0', '\0'};

    char hour[3] = {'0', '0', '\0'};
    char min[3] = {'0', '0', '\0'};
    char sec[3] = {'0', '0', '\0'};

    char msec[4] = {'0', '0', '0', '\0'};

    int timezone = -1;

    char *str, *a, *b, *hms, *tz;

    tz = strchr(timestr, '+');
    if (!tz) {
        tz = strchr(timestr, 'E');
        if (!tz) {
            tz = strchr(timestr, 'W');
            if (!tz) {
                // -08:00 or -08.00
                tz = strrchr(timestr, '-');
                if (tz) {
                    if (tz[1] && tz[2] && (tz[3] == ':' || tz[3] == '.')) {
                        // has timezone
                        // tz;
                    } else {
                        // no timezone
                        tz = 0;
                    }
                }
            }
        }
    }

    if (tz) {
        timezone = cstr_parse_timezone(tz);
        if (timezone == -1) {
            // error timezone
            return (-1);
        }
        *tz = 0;
    }

    str = cstr_LRtrim_whitespace(timestr);
    a = strchr(str, 39);
    b = strrchr(str, 39);

    if (a && b) {
        *a++ = 0;
        *b-- = 0;
        str = a;
        len = (int)(b - a) + 1;
    } else if (a || b) {
        // error char
        return (-1);
    } else {
        len = cstr_length(str, 30);
    }

    if (len == 10) {
        /* 2019-12-22 */
        YMD = 1;

        a = strchr(str, '-');
        b = strrchr(str, '-');

        if (a && b && a - str == 4 && b-a == 3) {
            *a++ = 0;
            *b++ = 0;

            vsnprintf_chkd(Year, sizeof(Year), "%.*s", 4, str);
            vsnprintf_chkd(Mon, sizeof(Mon), "%.*s", 2, a);
            vsnprintf_chkd(Day, sizeof(Day), "%.*s", 2, b);
        } else {
            // error date format
            return (-1);
        }
    } else if (len == 19) {
        /* 2019-12-22 12:36:59 */
        YMD = 1;
        HMS = 1;

        a = strchr(str, 32);
        if (a && a - str == 10) {
            *a++ = 0;

            hms = a;

            a = strchr(str, '-');
            b = strrchr(str, '-');

            if (a && b && a - str == 4 && b-a == 3) {
                *a++ = 0;
                *b++ = 0;

                vsnprintf_chkd(Year, sizeof(Year), "%.*s", 4, str);
                vsnprintf_chkd(Mon, sizeof(Mon), "%.*s", 2, a);
                vsnprintf_chkd(Day, sizeof(Day), "%.*s", 2, b);
            } else {
                // error date format
                return (-1);
            }

            a = strchr(hms, ':');
            b = strrchr(hms, ':');

            if (a && b && a - hms == 2 && b-a == 3) {
                *a++ = 0;
                *b++ = 0;

                vsnprintf_chkd(hour, sizeof(hour), "%.*s", 2, hms);
                vsnprintf_chkd(min, sizeof(min), "%.*s", 2, a);
                vsnprintf_chkd(sec, sizeof(sec), "%.*s", 2, b);
            } else {
                // error date format
                return (-1);
            }
        } else {
            // error datetime format
            return (-1);
        }
    } else if (len == 23) {
        /* 2019-12-22 12:36:59.065 */
        YMD = 1;
        HMS = 1;
        MMM = 1;

        a = strchr(str, 32);
        if (a && a - str == 10) {
            *a++ = 0;

            hms = a;

            a = strchr(str, '-');
            b = strrchr(str, '-');

            if (a && b && a - str == 4 && b-a == 3) {
                *a++ = 0;
                *b++ = 0;

                vsnprintf_chkd(Year, sizeof(Year), "%.*s", 4, str);
                vsnprintf_chkd(Mon, sizeof(Mon), "%.*s", 2, a);
                vsnprintf_chkd(Day, sizeof(Day), "%.*s", 2, b);
            } else {
                // error date format
                return (-1);
            }

            a = strchr(hms, ':');
            b = strrchr(hms, ':');

            if (a && b && a - hms == 2 && b-a == 3) {
                char *dot = strchr(b, '.');
                if (!dot || dot - b != 3) {
                    // error stamp format
                    return (-1);
                }

                *a++ = 0;
                *b++ = 0;
                *dot++ = 0;

                vsnprintf_chkd(hour, sizeof(hour), "%.*s", 2, hms);
                vsnprintf_chkd(min, sizeof(min), "%.*s", 2, a);
                vsnprintf_chkd(sec, sizeof(sec), "%.*s", 2, b);

                if (*dot) {
                    msec[0] = *dot++;

                    if (*dot) {
                        msec[1] = *dot++;

                        if (*dot) {
                            msec[2] = *dot++;
                        }
                    }
                }
            } else {
                // error date format
                return (-1);
            }
        } else {
            // error datetime format
            return (-1);
        }
    } else {
        // error format
        return (-1);
    }

    if (! YMD) {
        // no year
        return (-1);
    }

    if (cstr_isdigit(Year, 4) &&
        cstr_isdigit(Mon, 2) &&
        cstr_isdigit(Day, 2) &&
        cstr_isdigit(hour, 2) &&
        cstr_isdigit(min, 2) &&
        cstr_isdigit(sec, 2) &&
        cstr_isdigit(msec, 3)) {
        ub8 tsec;
        struct tm t = {0};

        t.tm_year = atoi(Year);
        t.tm_mon = atoi(Mon);
        t.tm_mday = atoi(Day);

        t.tm_hour = atoi(hour);
        t.tm_min = atoi(min);
        t.tm_sec = atoi(sec);

        if (! time_is_valid(t.tm_year, t.tm_mon, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec)) {
            // invalid time
            return (-1);
        }

        t.tm_year -= 1900;
        t.tm_mon  -= 1;

        // since 1970-01-01 UTChh:00:00 (china: hh=8)
        tsec = (ub8) mktime(&t);
        if (tsec == (ub8)(-1)) {
            return (-1);
        }

        if (outdt) {
            outdt->year = atoi(Year);
            outdt->month = atoi(Mon);
            outdt->day = atoi(Day);

            outdt->hour = atoi(hour);
            outdt->minute = atoi(min);
            outdt->second = atoi(sec);
            outdt->millisecond = atoi(msec);

            outdt->timezone = timezone;
        }

        if (! HMS) {
            outdt->hour = -1;
            outdt->minute = 0;
            outdt->second = 0;
        }
        if (! MMM) {
            outdt->millisecond = -1;
        }

        tsec *= 1000;
        return (ub8)(tsec + atoi(msec));
    }

    // error no digit
    return (-1);
}

/**
 * @brief 将毫秒级时间戳字符串转换为格式化的日期时间字符串
 *
 * 接收以字符串形式存储的毫秒级时间戳（如 "1623456789123"），解析为数值后转换为本地时区的日期时间，
 * 格式化为 "YYYY-MM-DD HH:MM:SS" 或 "YYYY-MM-DD HH:MM:SS.fff"（含毫秒，毫秒非零时），结果存入输出缓冲区。
 *
 * @param stampms 输入的毫秒级时间戳字符串（需为十进制数字，非 NULL）
 * @param mslen 时间戳字符串的长度；若为 -1，自动调用 `cstr_length` 计算（最大限制 20 字节，避免超长）
 * @param timestr 输出的日期时间字符串缓冲区（需预先分配至少 24 字节空间，用于存储最长格式 "YYYY-MM-DD HH:MM:SS.fff"）
 *
 * @return const char*
 *   - 成功：返回 `timestr`（指向格式化后的日期时间字符串）
 *   - 失败：返回 NULL（时间戳解析失败、本地时间转换失败或日期时间无效）
 *
 * @note 时间戳解析规则：
 *       1. 输入 `stampms` 需为纯十进制数字字符串（如 "1623456789123" 表示 1623456789 秒 + 123 毫秒）
 *       2. 解析后存储为 64 位无符号整数（`ub8`），支持最大时间戳约为 1.8e19 毫秒（覆盖未来极长时间）
 * @note 跨平台时间转换：
 *       - Windows 平台使用 `localtime_s`（线程安全）
 *       - 其他平台使用 `localtime_r`（线程安全，避免 `localtime` 的线程不安全问题）
 * @note 依赖函数：
 *       1. `cstr_length`：计算时间戳字符串长度
 *       2. `cstr_to_ub8`：将字符串转换为 64 位无符号整数（`ub8`）
 *       3. `time_is_valid`：校验转换后的日期时间是否合法（如月份 1-12、日期 1-31 等）
 *       4. `vsnprintf_chkd`：安全格式化字符串（需确保其功能与 `snprintf` 兼容，且有缓冲区越界检查）
 * @note 忽略参数有效性检查（如 `stampms`/`timestr` 空指针、`timestr` 空间不足），依赖调用者保证参数合法
 */
const char * cstr_timestamp_to_datetime(char *stampms, size_t mslen, char timestr[24])
{
    ub8 stamp = 0;
    time_t tsec;
    int msec;
    struct tm t;

    if (cstr_invalid_size(mslen)) {
        mslen = cstr_length(stampms, 20);
    }

    if (cstr_to_ub8(10, stampms, mslen, &stamp, timestr, 24) > 0) {
        // error stamp
        return NULL;
    }

    tsec = (time_t)(stamp / 1000);
    msec = (int)(stamp % 1000);

#if defined(PLATFORM_WINDOWS)
    if (!localtime_s(&t, (const time_t*) &tsec)) {
        // error localtime
        return NULL;
    }
#else
    if (!localtime_r((const time_t*)&tsec, &t)) {
        // error localtime
        return NULL;
    }
#endif

    t.tm_year += 1900;
    t.tm_mon  += 1;

    if (! time_is_valid(t.tm_year, t.tm_mon, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec)) {
        // invalid time
        return NULL;
    }

    if (msec) {
        /* 2012-12-22 17:45:59.875 */
        vsnprintf_chkd(timestr, 24, "%04d-%02d-%02d %02d:%02d:%02d.%03d", t.tm_year, t.tm_mon, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec, msec);
    } else {
        vsnprintf_chkd(timestr, 20, "%04d-%02d-%02d %02d:%02d:%02d", t.tm_year, t.tm_mon, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec);
    }

    return timestr;
}

/**
 * @brief BKDR字符串哈希函数
 * @param str 输入字符串（如果为NULL则返回0）
 * @param seed 哈希种子（推荐使用质数：31, 131, 1313, 13131, 131313等）
 * @param table_size 哈希表大小（必须为0或2的幂次方：256, 1024, 2048等）
 * @return 哈希值：
 *         - 如果table_size=0，返回完整的32位哈希值（0x7FFFFFFF范围内）
 *         - 如果table_size>0，返回在[0, table_size-1]范围内的哈希索引
 *
 * @note 哈希算法：BKDRHash (Brian Kernighan和Dennis Ritchie)
 * @note 当table_size>0时，必须保证table_size是2的幂次方，否则结果不正确
 * @note 种子选择质数可以减少哈希冲突
 *
 * @example
 * // 基本哈希值
 * unsigned int hash = cstr_bkdr_hash("hello", 131, 0);
 *
 * // 哈希表索引（table_size必须是2的幂）
 * unsigned int index = cstr_bkdr_hash("key", 131, 1024); // 返回0-1023
 *
 * @see 参考经典的BKDR哈希算法实现
 */
unsigned int cstr_bkdr_hash(const char *str, unsigned int seed, unsigned int table_size)
{
    /*
     * seed = 131, 1313, 13131 131313 etc..
     * table_size = 0, 256, 1024, 2048, ...
    */
    if (str == NULL) {
        return 0;
    }
    unsigned int hash = 0;
    unsigned char *ustr = (unsigned char *)str;
    while (*ustr) {
        hash = hash * seed + (*ustr++);
    }

    hash = (hash & 0x7FFFFFFF);
    return table_size ? (hash & (table_size - 1)) : hash;
}

