/**
 * @brief 安全获取字符串缓冲区中指定索引的字符指针（边界检查）
 *
 * 检查索引是否在有效范围内，若有效则返回对应位置的字符指针，否则返回 NULL。
 *
 * @param csb 字符串缓冲区（cstrbuf 类型，非 NULL 且有效）
 * @param at 目标字符的索引（0 基，需 >= 0 且 < 缓冲区长度）
 *
 * @return char*
 *   - 成功：返回索引 at 处的字符指针（指向 csb->str[at]）
 *   - 失败：返回 NULL（索引越界或缓冲区无效）
 *
 * @note 依赖 `cstrbufGetLen` 函数获取缓冲区当前长度
 * @note 忽略参数有效性检查，调用者需确保 csb 为合法缓冲区
 */
char * cstrbufCharAtSafe(cstrbuf csb, int at)
{
    int len = cstrbufGetLen(csb);
    if (at >= 0 && at < len) {
        return cstrbufCharAt(csb, at);
    }
    // invalid cstrbuf or index
    return NULL;
}

/**
 * @brief 创建新的字符串缓冲区并初始化
 *
 * 根据指定的最大容量、初始字符串及长度，创建并初始化一个 cstrbuf 缓冲区，
 * 自动处理容量对齐和内存分配，确保字符串以 '\0' 结尾。
 *
 * @param maxsz 期望的最大容量（字节）；0 表示自动计算，特殊值 `cstrbuf_error_size` 表示按内容扩容
 * @param str 初始字符串（可为 NULL，此时创建空缓冲区）
 * @param len 初始字符串的长度；特殊值 `cstrbuf_error_size` 表示自动调用 `cstr_length` 计算长度
 *
 * @return cstrbuf
 *   - 成功：返回新创建的字符串缓冲区（已初始化，str 内容已复制）
 *   - 失败：内存分配失败时返回 NULL（未显式处理，依赖 `mem_alloc` 的行为）
 *
 * @note 容量处理逻辑：
 *       - 若 maxsz 为 0：容量设为 len + 1
 *       - 若 maxsz 无效或 <= len：容量设为 `cstrbuf_alignsize(len + 1)`（对齐后的值）
 *       - 否则：容量设为 `cstrbuf_alignsize(maxsz)`（对齐后的值）
 * @note 初始字符串为 NULL 时，缓冲区初始化为空（len=0，str[0]='\0'）
 */
cstrbuf cstrbufNew(ub4 maxsz, const char *str, ub4 len)
{
    cstrbuf_t *csb;

    if (len == cstrbuf_error_size) {
        len = (ub4) cstr_length(str, cstr_length_max);
    }

    if (! maxsz) {
        maxsz = len + 1;
    } else if (maxsz == cstrbuf_error_size) {
        maxsz = cstrbuf_alignsize(len + 1);
    } else if (maxsz <= len) {
        maxsz = cstrbuf_alignsize(len + 1);
    } else {
        // maxsz > len
        maxsz = cstrbuf_alignsize(maxsz);
    }

    csb = (cstrbuf_t *) mem_alloc(sizeof(*csb) + maxsz);

    csb->__maxszlen = 0;
    *csb->str = 0;

    if (str) {
        memcpy(csb->str, str, len);
        memset(csb->str + len, 0, maxsz - len);
        csb->len = len;
    } else {
        memset(csb->str, 0, maxsz);
        csb->len = 0;
    }

    csb->maxsz = maxsz;
    return csb;
}

/**
 * @brief 创建指定最大长度的字符串缓冲区并初始化
 *
 * 简化版创建函数，直接按指定最大长度分配内存，复制初始字符串的前 maxlen 个字符并确保终止符。
 *
 * @param str 初始字符串（可为 NULL，此时创建空缓冲区）
 * @param maxlen 字符串的最大有效长度（不含终止符 '\0'），实际分配容量为 maxlen + 1（含终止符）
 *               如果为 -1，则自动计算字符串长度
 * @return cstrbuf
 *   - 成功：返回新创建的缓冲区（str 内容已复制，长度为实际有效字符数）
 *   - 失败：内存分配失败时返回 NULL（依赖 `mem_alloc` 的行为）
 *
 * @note 初始字符串长度超过 maxlen 时，仅复制前 maxlen 个字符（通过 `cstr_length` 控制）
 * @note 始终确保缓冲区末尾有 '\0' 终止符（str[len] = '\0'）
 */
cstrbuf cstrbufNew2(const char* str, ub4 maxlen)
{
    ub4 slen = 0;
    if (maxlen == (ub4)(-1)) {
        maxlen = (ub4) strlen(str);
        slen = maxlen;
    }

    cstrbuf_t* csb = (cstrbuf_t*)mem_alloc(sizeof(*csb) + maxlen + 1);
    csb->len = slen? slen : (ub4) cstr_length(str, maxlen);
    if (csb->len) {
        memcpy(csb->str, str, csb->len);
    }
    csb->maxsz = maxlen + 1;
    csb->str[csb->len] = '\0';
    return csb;
}

/**
 * @brief 释放字符串缓冲区并置空指针
 *
 * 安全释放 cstrbuf 缓冲区的内存，并将输入指针置空（避免悬垂指针）。
 *
 * @param csb 指向字符串缓冲区指针的指针（若为 NULL 则不操作）
 *
 * @note 若 csb 非 NULL 但指向的缓冲区为 NULL（*csb = NULL），则不执行释放操作
 * @note 依赖 `mem_free` 函数释放内存，需确保缓冲区由 `mem_alloc` 或 `mem_realloc` 分配
 */
void cstrbufFree(cstrbuf *csb)
{
    if (csb) {
        cstrbuf s = *csb;
        if (s) {
            *csb = 0;
            mem_free(s);
        }
    }
}

/**
 * @brief 将字符串缓冲区内容复制到目标缓冲区
 *
 * 从源缓冲区复制字符串内容到目标缓冲区的指定偏移位置，返回更新后的偏移。
 *
 * @param src 源字符串缓冲区（可为 NULL，此时不复制）
 * @param dstbuf 目标缓冲区（需预先分配足够内存）
 * @param offcb 目标缓冲区的起始偏移位置（复制从该位置开始）
 *
 * @return ub4
 *   - 成功：返回复制后目标缓冲区的新偏移（offcb + src->len）
 *   - 无操作：src 为 NULL 或 src->len 为 0 时，返回原始 offcb
 *
 * @note 注释要求“dstbuf 必须有足够空间”，函数不做空间检查，依赖调用者保证
 * @note 仅复制有效字符（src->str 的前 src->len 字节），不包含终止符 '\0'
 */
ub4 cstrbufCopyTo(const cstrbuf src, void *dstbuf, ub4 offcb)
{
    if (src && src->len) {
        memcpy((char*)dstbuf + offcb, src->str, src->len);
        return (ub4)(offcb + src->len);
    }
    return (ub4)offcb;
}

/**
 * @brief 将格式化的字符串复制到目标
 *
 * 将格式化的字符串复制到目标，返回更新后的目标。
 *
 * @param dst 目标（可为 NULL）
 * @param fmt 格式化字符串（同 printf 格式）
 *
 * @return 新目标
 *   - 成功：非 NULL，返回复制后目标（如果旧目标没有重用，则释放，否则返回原目标）
 *   - 失败：NULL，内存不足或无法格式化 (原目标不会更改)
 *
 * @note dst 如果有足够空间，则复用 dst，否则释放后重建
 */
cstrbuf cstrbufCopyFrom(cstrbuf dst, const char *fmt, ...)
{
    int len;
    cstrbuf dst_saved = dst;

    va_list args;

    // 首先计算格式化字符串的长度
    va_start(args, fmt);
    len = vsnprintf(NULL, 0, fmt, args);
    va_end(args);

    if (len < 0) {
        // 失败返回 NULL
        // 注意：这里不释放原始dst
        return NULL;
    }

    if (! dst) {
        // 创建新缓冲区
        dst = cstrbufNew2(NULL, len);
        if (! dst) {
            return NULL;  // should never run to this!
        }
    } else if (dst->maxsz < (ub4)(len + 1)) {
        // 现有缓冲区空间不足，需要重新分配
        cstrbuf new_dst = (cstrbuf) cstrbufNew2(NULL, len);
        if (!new_dst) {
            return NULL;  // should never run to this!
        }
        dst = new_dst;
    }

    // 现在将格式化字符串复制到缓冲区
    va_start(args, fmt);
    len = vsnprintf(dst->str, dst->maxsz, fmt, args);
    va_end(args);

    if (len < 0) {
        // 如果这是新分配的缓冲区，需要释放它
        if (dst != dst_saved) {
            cstrbufFree(&dst);
        }
        return NULL;
    }

    dst->len = len;
    dst->str[dst->len] = 0;

    if (dst != dst_saved) {
        // 如果这是新分配的缓冲区，需要释放原缓冲区
        cstrbufFree(&dst_saved);
    }

    // 成功返回
    return dst;
}

/**
 * @brief 向字符串缓冲区追加格式化字符串（支持自动扩容）
 *
 * 若缓冲区为 NULL 则创建新缓冲区；否则追加格式化字符串，空间不足时自动扩容，确保字符串有效终止。
 *
 * @param dst 目标字符串缓冲区（可为 NULL，此时创建新缓冲区）
 * @param fmt 格式化字符串（同 printf 格式）
 * @param ... 可变参数列表（与 fmt 匹配的参数）
 *
 * @return cstrbuf
 *   - 成功：返回更新后的缓冲区（新创建或扩容后的原缓冲区）
 *   - 失败：格式化失败或内存分配失败时返回 NULL（并释放已分配内存）
 *
 * @note 扩容逻辑：当现有空间不足时，通过 `cstrbuf_alignsize` 计算新容量，调用 `mem_realloc` 扩容
 * @note 依赖 `vsnprintf` 获取字符串长度和格式化内容，错误时打印日志
 * @note 始终确保缓冲区末尾有 '\0' 终止符
 */
cstrbuf cstrbufCat(cstrbuf dst, const char *fmt, ...)
{
    int vlen, len;

    if (! dst) {
        do {
            va_list args;
            va_start(args, fmt);
            vlen = vsnprintf(0, 0, fmt, args);
            va_end(args);
        } while(0);

        if (vlen < 0) {
            return 0;
        }

        dst = cstrbufNew(vlen + 1, 0, 0);

        do {
            va_list args;
            va_start(args, fmt);
            len = vsnprintf(dst->str, dst->maxsz, fmt, args);
            va_end(args);
        } while(0);

        if (len == vlen) {
            dst->len = len;
            dst->str[dst->len] = 0;
            return dst;
        }
        cstrbufFree(&dst);
        return 0;
    } else {
        do {
            va_list args;
            va_start(args, fmt);
            vlen = vsnprintf(&dst->str[dst->len], dst->maxsz - dst->len, fmt, args);
            va_end(args);
        } while(0);

        if (vlen < 0) {
            dst->str[dst->len] = 0;
            return dst;
        }

        if (dst->len + vlen < dst->maxsz) {
            dst->len += vlen;
            dst->str[dst->len] = 0;
            return dst;
        } else {
            ub4 maxsz = cstrbuf_alignsize(dst->len + vlen + 1);
            cstrbuf_t *newdst = (cstrbuf_t *) mem_realloc(dst, sizeof(*newdst) + maxsz);
            if (! newdst) {
                _exit(EXIT_FAILURE);
            }
            newdst->maxsz = maxsz;

            do {
                va_list args;
                va_start(args, fmt);
                len = vsnprintf(&newdst->str[newdst->len], newdst->maxsz - newdst->len, fmt, args);
                va_end(args);
            } while(0);

            if (len == vlen) {
                newdst->len += len;
            }

            newdst->str[newdst->len] = 0;
            return newdst;
        }
    }
}

/**
 * @brief 截断字符串缓冲区（支持正负索引）
 *
 * 根据偏移量截断缓冲区内容，调整长度并确保终止符有效。
 *
 * @param s 目标字符串缓冲区（非 NULL 且有效）
 * @param offset 截断偏移量：
 *               - 正值：截断到 offset 位置（保留前 offset 个字符，若 offset >= 当前长度则不操作）
 *               - 负值：从末尾截断 |offset| 个字符（若结果 < 0 则截断为空）
 *
 * @return cstrbuf 返回截断后的缓冲区（与输入 s 相同，无内存分配）
 *
 * @note 截断后自动设置终止符（s->str[s->len] = '\0'）
 * @note 不修改缓冲区容量（maxsz 不变），仅调整长度（len）
 */
cstrbuf cstrbufTrunc(cstrbuf s, int offset)
{
    if (offset >= 0) {
        if ((int) s->len > offset) {
            s->len = offset;
        }
    } else {
        if ((int)s->len + offset >= 0) {
            s->len += offset;
        } else {
            s->len = 0;
        }
    }
    s->str[s->len] = '\0';
    return s;
}

/**
 * @brief 拼接多个字符串缓冲区（以 NULL 结尾）
 *
 * 从可变参数列表中拼接多个 cstrbuf 缓冲区内容，返回新的缓冲区（包含所有内容的拼接结果）。
 *
 * @param start 第一个待拼接的字符串缓冲区（可为 NULL，此时返回空缓冲区）
 * @param ... 后续待拼接的字符串缓冲区，必须以 NULL 结束
 *
 * @return cstrbuf
 *   - 成功：返回新创建的缓冲区（包含所有输入缓冲区的拼接内容）
 *   - 失败：内存分配失败时返回 NULL（依赖 `cstrbufCat` 的错误处理）
 *
 * @note 内部通过 `cstrbufCat` 实现拼接，自动处理内存分配和扩容
 * @note 若所有输入缓冲区均为空，则返回空缓冲区（len=0）
 */
cstrbuf cstrbufConcat(const cstrbuf start, ...)
{
    va_list argp;
    cstrbuf src = start;
    va_start(argp, start);
    cstrbuf result = 0;

    do {
        result = cstrbufCat(result, "%.*s", cstrbufGetLen(src), cstrbufGetStr(src));
        src = va_arg(argp, cstrbuf);
    } while(src);

    va_end(argp);
    return result;
}

/**
 * @brief 复制源字符串到目标缓冲区（复用或创建新缓冲区）
 *
 * 若目标缓冲区为 NULL 则创建新缓冲区；否则复用目标缓冲区（空间足够时直接复制，不足时重新分配）。
 *
 * @param dst 目标缓冲区（可为 NULL，此时创建新缓冲区）
 * @param source 源字符串（非 NULL，需以 '\0' 结尾）
 * @param sourcelen 源字符串长度；特殊值 `cstrbuf_error_size_len` 表示自动计算长度
 *
 * @return cstrbuf
 *   - 成功：返回更新后的目标缓冲区（复用或新创建）
 *   - 失败：内存分配失败时返回 NULL（依赖 `cstrbufNew` 的行为）
 *
 * @note 源字符串长度为 0 时，目标缓冲区被清空（len=0，str[0]='\0'）
 * @note 若目标缓冲区空间不足，会释放原缓冲区并创建新缓冲区（原指针失效）
 */
cstrbuf cstrbufDup(cstrbuf dst, const char *source, ub4 sourcelen)
{
    if (! dst) {
        return cstrbufNew(0, source, sourcelen);
    }

    if (sourcelen == cstrbuf_error_size) {
        sourcelen = (ub4) cstr_length(source, -1);
    }

    if (! sourcelen) {
        dst->len = 0;
        dst->str[dst->len] = 0;
        return dst;
    }

    if (dst->maxsz > sourcelen) {
        memcpy(dst->str, source, sourcelen);

        dst->len = sourcelen;
        dst->str[dst->len] = 0;
        return dst;
    }

    mem_free(dst);
    return cstrbufNew(0, source, sourcelen);
}

/**
 * @brief 替换字符串中的指定片段（返回新缓冲区）
 *
 * 在源字符串中，将从 startindex 开始的 length 长度片段替换为 substr，返回包含结果的新缓冲区。
 *
 * @param source 源字符串（非 NULL，需以 '\0' 结尾）
 * @param startindex 替换起始索引（0 基，需在源字符串长度范围内）
 * @param length 待替换的长度（需 >= 0，且 startindex + length <= 源字符串长度）
 * @param substr 替换字符串（非 NULL）
 * @param sublen 替换字符串的长度（需 >= 0）
 *
 * @return cstrbuf 返回新创建的缓冲区（包含替换后的结果）
 *
 * @note 内部通过以下步骤实现：
 *       1. 创建存储源字符串后半部分（替换位置之后）的缓冲区 endstr
 *       2. 创建存储源字符串前半部分（替换位置之前）的缓冲区 result
 *       3. 复制 substr 到 result 的替换位置，再复制 endstr 到其后
 *       4. 释放 endstr 并返回 result
 * @note 新缓冲区长度为：源长度 - length + sublen
 */
cstrbuf cstrbufSub(const char *source, int startindex, int length, const char *substr, int sublen)
{
    int sourlen = cstr_length(source, -1);

    cstrbuf endstr = cstrbufNew(0, source + startindex + length, sourlen - startindex - length);
    cstrbuf result = cstrbufNew(sourlen - length + sublen + 1, source, startindex);

    memcpy(result->str + startindex, substr, sublen);
    memcpy(result->str + startindex + sublen, endstr->str, endstr->len);

    cstrbufFree(&endstr);

    result->len = sourlen - length + sublen;
    result->str[result->len] = 0;

    return result;
}

/**
 * @brief 向字符串缓冲区末尾追加单个字符（自动扩容）
 *
 * 在缓冲区末尾添加一个字符，空间不足时自动扩容（通过 `cstrbufCat` 实现）。
 *
 * @param dst 目标缓冲区（可为 NULL，此时创建新缓冲区）
 * @param ch 待追加的字符
 *
 * @return cstrbuf
 *   - 成功：返回更新后的缓冲区（原缓冲区或扩容后的新缓冲区）
 *   - 失败：内存分配失败时返回 NULL（依赖 `cstrbufCat` 的错误处理）
 *
 * @note 空间检查：若当前长度 + 1 < 最大容量，直接追加；否则调用 `cstrbufCat` 扩容
 * @note 缓冲区为 NULL 时，通过 `cstrbufCat` 创建仅包含 ch 的新缓冲区
 */
cstrbuf cstrbufPushBack(cstrbuf dst, char ch)
{
    if (dst) {
        if (dst->len + 1 < dst->maxsz) {
            dst->str[dst->len++] = ch;
        } else {
            dst = cstrbufCat(dst, "%c", ch);
        }
    } else {
        dst = cstrbufCat(NULL, "%c", ch);
    }
    return dst;
}
