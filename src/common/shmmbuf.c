#define SHMMBUF_VERIFY_STATE(val)  if ((val) == SHMMBUF_INVALID_STATE) emerglog_error_exit("shmmbuf.c", "SHMMBUF_INVALID_STATE")

#define SHMMBUF_FATAL_BUG(errmsg)  emerglog_error_exit("shmmbuf.c", errmsg)

