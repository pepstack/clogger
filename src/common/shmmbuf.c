/**
 * @brief Internal read implementation (not for direct use)
 * @param shmbuf Shared memory buffer
 * @param wrap Wrap state
 * @param Ro Raw read offset
 * @param Wo Raw write offset
 * @param L Buffer length
 * @param nextentry_cb Entry callback
 * @param arg Callback context
 * @return Read status code
 */
static int _shmmap_buffer_read_internal(shmmap_buffer shmbuf, ssize_t wrap, ssize_t Ro, ssize_t Wo, ssize_t L,
    int (*nextentry_cb)(const shmmbuf_entry, void*), void* arg)
{
    shmmbuf_entry_t* entry;

    ssize_t AENTSZ,
        HENTSZ = (ssize_t)SHMMBUF_ALIGN_ENTRYSIZE(0);

    ssize_t R = Ro % L;
    ssize_t W = Wo % L;

    //DEBUG_PRINT("(shmmbuf.h:%d) shmmap_buffer_read_next():wrap=%d W=%" PRId64" R=%" PRId64" L=%" PRId64"\n",
    //    __LINE__, (int)wrap, W, R, L);

    /* Sr = f*L + W - R */
    if (wrap * L + W - R > HENTSZ) {
        if (wrap) {  /* wrap(1): 0 .. W < R < L */
            if (L - R > HENTSZ) {
                entry = SHMMBUF_ENTRY_CAST(&shmbuf->Buffer[R]);
                if (entry->size) {
                    AENTSZ = SHMMBUF_ALIGN_ENTRYSIZE(entry->size);

                    if (L - R >= AENTSZ) {
                        if (nextentry_cb(entry, arg)) {
                            /* read success and set ROffset to next entry */
                            R = SHMRINGBUF_NORMALIZE_OFFSET(Ro + AENTSZ, L);
                            shmmbuf_state_set(&shmbuf->ROffset, R);

                            return SHMMBUF_READ_NEXT;
                        }
                        else {
                            /* read paused by caller */
                            return SHMMBUF_READ_AGAIN;
                        }
                    }

                    SHMMBUF_FATAL_BUG("SHMMBUF_READ_FATAL");
                    return SHMMBUF_READ_FATAL;
                }
                else {
                    /* reset ROffset to 0 (set wrap = 0) */
                    shmmbuf_state_set(&shmbuf->ROffset, (Wo / L) * L);

                    return shmmap_buffer_read_next(shmbuf, nextentry_cb, arg);
                }
            }
            else if (W - 0 > HENTSZ) {
                /* reset ROffset to 0 */
                entry = SHMMBUF_ENTRY_CAST(&shmbuf->Buffer[0]);
                if (entry->size) {
                    AENTSZ = SHMMBUF_ALIGN_ENTRYSIZE(entry->size);

                    if (W - 0 >= AENTSZ) {
                        if (nextentry_cb(entry, arg)) {
                            /* read success and set ROffset to next entry */
                            shmmbuf_state_set(&shmbuf->ROffset, AENTSZ + (Wo / L) * L);

                            return SHMMBUF_READ_NEXT;
                        }
                        else {
                            /* read paused by caller */
                            return SHMMBUF_READ_AGAIN;
                        }
                    }
                }

                SHMMBUF_FATAL_BUG("SHMMBUF_READ_FATAL");
                return SHMMBUF_READ_FATAL;
            }
        }
        else {  /* wrap(0): 0 .. R < W < L */
            entry = SHMMBUF_ENTRY_CAST(&shmbuf->Buffer[R]);
            if (entry->size) {
                AENTSZ = SHMMBUF_ALIGN_ENTRYSIZE(entry->size);

                if (W - R >= AENTSZ) {
                    if (nextentry_cb(entry, arg)) {
                        /* read success and set ROffset to next entry */
                        R = SHMRINGBUF_NORMALIZE_OFFSET(Ro + AENTSZ, L);
                        shmmbuf_state_set(&shmbuf->ROffset, R);

                        return SHMMBUF_READ_NEXT;
                    }
                    else {
                        /* read paused by caller */
                        return SHMMBUF_READ_AGAIN;
                    }
                }
            }

            SHMMBUF_FATAL_BUG("SHMMBUF_READ_FATAL");
            return SHMMBUF_READ_FATAL;
        }
    }

    /* no entry to read, retry again */
    return SHMMBUF_READ_AGAIN;
}
