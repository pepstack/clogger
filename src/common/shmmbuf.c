/* Alignment macros */
#define SHMMBUF_ALIGN_BSIZE(bsz, alignsize)  ((size_t)((((size_t)(bsz)+(alignsize)-1)/(alignsize))*(alignsize)))

#define SHMMBUF_ALIGN_PAGESIZE(fsz)  SHMMBUF_ALIGN_BSIZE((fsz), SHMMBUF_PAGE_SIZE)

