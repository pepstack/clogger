/**
 * @brief 格式化 Windows 系统错误信息
 *
 * 此函数将 Windows 系统错误代码转换为可读的错误消息字符串。
 * 如果传入的错误代码为 (DWORD)-1，则自动获取当前线程的最后错误代码。
 *
 * @param dwError Windows 错误代码。如果传入 (DWORD)-1，则使用 GetLastError() 获取当前错误代码
 * @param errbuf 存储错误信息的输出缓冲区。必须至少为 128 字节
 * @param bufsize errbuf 缓冲区的字节大小。必须至少为 128
 * @return const char* 指向格式化后的错误信息字符串的指针（即 errbuf）
 *
 * @note 如果 FormatMessageA 调用失败，函数将返回包含原始错误代码 dwError 和
 *       FormatMessageA 失败错误代码 LastError 的备用错误消息。
 *       错误代码 dwError 将同时以十进制 (%lu) 和十六进制 (0x%08lX) 格式显示，
 *       便于在微软文档和调试器中查找。
 *
 *       返回的字符串 errbuf 是 null-ended，并且移除了末尾的换回符。
 *
 * @example
 *   char errmsg[256];
 *   if (!SomeWindowsAPI()) {
 *       FormatWindowsError(GetLastError(), errmsg, sizeof(errmsg));
 *       printf("Error: %s\n", errmsg);
 *   }
 */
const char* FormatWindowsError(DWORD dwError, char errbuf[], size_t bufsize)
{
    if (bufsize < 2) {
        errbuf[0] = '\0';
        return errbuf;
    }

    DWORD dwRet;
    if (dwError == (DWORD)-1) {
        dwError = GetLastError();
    }

    const DWORD dwEngLang = MAKELANGID(LANG_ENGLISH, SUBLANG_ENGLISH_US);
    const DWORD dwDefLang = MAKELANGID(LANG_NEUTRAL, SUBLANG_DEFAULT);

    dwRet = FormatMessageA(FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS,
                NULL,
                dwError,
                dwEngLang,
                errbuf,
                (DWORD)bufsize,
                NULL);
    if (!dwRet && dwDefLang != dwEngLang) {
        dwRet = FormatMessageA(FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS,
            NULL,
            dwError,
            dwDefLang,
            errbuf,
            (DWORD)bufsize,
            NULL);
    }

    if (!dwRet) {
        DWORD fmtError = GetLastError();
        snprintf(errbuf, bufsize,
            "FormatMessageA failed for dwError=%" PRIu32 " (0x%08" PRIx32 ") with LastError=%" PRIu32,
            (uint32_t) dwError,
            (uint32_t) dwError,
            (uint32_t) fmtError
        );
        errbuf[bufsize - 1] = '\0';
    }
    else if (dwRet > 0) {
        // 成功获取错误消息，移除末尾的回车和换行符
        if (dwRet >= bufsize) {
            dwRet = (DWORD)(bufsize - 1);
        }
        char *p = errbuf + dwRet;
        *p-- = '\0';
        while (p >= errbuf && (*p == '\r' || *p == '\n' || *p == ' ')) {
            *p-- = '\0';
        }
    }
    else {
        // should never run to this.
        errbuf[0] = '\0';
    }
    return errbuf;
}
