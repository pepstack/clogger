#include "ringbufst.h"

#include "memapi.h"
#include "uatomic.h"


#if defined(PLATFORM_WINDOWS)
    #define INT_CAST_TO_ATOMIC(s)  ((LONG)(s))
#else
    #define INT_CAST_TO_ATOMIC(s)  ((int)(s))
#endif

/**
 * Below definitions SHOULD NOT be changed!
 */
#define RINGBUFST_PAGE_SIZE        ((size_t)4096)

#define RINGBUFST_INVALID_STATE    ((ssize_t)(-1))

#define RINGBUFST_ENTRY_HDRSIZE    (sizeof(ringbuffer_entry_st))

#define RINGBUFST_ALIGN_PAGESIZE(fsz)  memapi_align_bsize((fsz), RINGBUFST_PAGE_SIZE)

#define RINGBUFST_ALIGN_ENTRYSIZE(chunksize)  memapi_align_bsize((chunksize + RINGBUFST_ENTRY_HDRSIZE), RINGBUFST_ENTRY_HDRSIZE)

#define RINGBUFST_ENTRY_CAST(p)  ((ringbuffer_entry_st *)(p))


/**
 * static memory layout of ring buffer.
 * see also:
 *   ringbuf.h
 */
typedef struct _ring_buffer_st
{
    /* Read Lock */
    UAtomicInt RLock;

    /* Write Lock */
    UAtomicInt WLock;

    /* Write Offset to the Buffer start */
    UAtomicInt WOffset;

    /* Read Offset to the Buffer start */
    UAtomicInt ROffset;

    /* Length of ring Buffer: total size in bytes */
    size_t Length;

    /* ring buffer static memory with Length */
    uint8_t Buffer[0];
} ring_buffer_st;


#define RINGBUFST_RESTORE_WRAP(Ro, Wo, L)  \
    ((ssize_t)((Ro)/(L) == (Wo)/(L) ? 0 : 1))


#define RINGBUFST_RESTORE_STATE(Ro, Wo, L)  \
    ssize_t wrap = RINGBUFST_RESTORE_WRAP(Ro, Wo, L); \
    ssize_t R = (ssize_t)((Ro) % (L)); \
    ssize_t W = (ssize_t)((Wo) % (L))


#define RINGBUFST_NORMALIZE_OFFSET(Ao, L)  \
    ((((Ao)/(L))%2)*L + (Ao)%(L))


static int ringbufst_read_internal(ringbufst_t rbst, ssize_t wrap, ssize_t Ro, ssize_t Wo, ssize_t L,
    int (*nextentry_cb)(const ringbufst_entry, void *), void *arg)
{
    ringbuffer_entry_st *entry;

    ssize_t AENTSZ,
            HENTSZ = (ssize_t)RINGBUFST_ALIGN_ENTRYSIZE(0);

    ssize_t R = Ro % L;
    ssize_t W = Wo % L;

    /* Sr = f*L + W - R */
    if (wrap*L + W - R > HENTSZ) {
        if (wrap) {  /* wrap(1): 0 .. W < R < L */
            if (L - R > HENTSZ) {
                entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[R]);
                if (entry->size) {
                    AENTSZ = RINGBUFST_ALIGN_ENTRYSIZE(entry->size);

                    if (L - R >= AENTSZ) {
                        if (nextentry_cb(entry, arg)) {
                            /* read success and set ROffset to next entry */
                            R = RINGBUFST_NORMALIZE_OFFSET(Ro + AENTSZ, L);
                            UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC(R));

                            return 1;
                        } else {
                            /* no entry to read, retry again(0) */
                            return 0;
                        }
                    }

                    assert(0 && "SHOULD NEVER RUN TO THIS!");
                    return (-1);
                } else {
                    /* reset ROffset to 0 (set wrap = 0) */
                    UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC((Wo/L) * L));

                    return ringbufst_read_next(rbst, nextentry_cb, arg);
                }
            } else if (W - 0 > HENTSZ) {
                /* reset ROffset to 0 */
                entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[0]);
                if (entry->size) {
                    AENTSZ = RINGBUFST_ALIGN_ENTRYSIZE(entry->size);

                    if (W - 0 >= AENTSZ) {
                        if (nextentry_cb(entry, arg)) {
                            /* read success and set ROffset to next entry */
                            UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC(AENTSZ + (Wo/L)*L));

                            return 1;
                        } else {
                            /* read paused by caller, retry again(0) */
                            return 0;
                        }
                    }
                }

                assert(0 && "SHOULD NEVER RUN TO THIS!");
                return (-1);
            }
        } else {  /* wrap(0): 0 .. R < W < L */
            entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[R]);
            if (entry->size) {
                AENTSZ = RINGBUFST_ALIGN_ENTRYSIZE(entry->size);

                if (W - R >= AENTSZ) {
                    if (nextentry_cb(entry, arg)) {
                        /* read success and set ROffset to next entry */
                        R = RINGBUFST_NORMALIZE_OFFSET(Ro + AENTSZ, L);
                        UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC(R));

                        return 1;
                    } else {
                        /* read paused by caller, retry again(0) */
                        return 0;
                    }
                }
            }

            assert(0 && "SHOULD NEVER RUN TO THIS!");
            return (-1);
        }
    }

    /* no entry to read, retry again(0) */
    return 0;
}


/* ======================== public interface ======================= */

ringbufst_t ringbufst_init(int length, size_t entrysize)
{
    ring_buffer_st *rbst;
    size_t rblen = memapi_align_bsize(length, 64);
    if (rblen > RINGBUFST_LEN_MAX) {
        rblen = RINGBUFST_LEN_MAX;
    }

    size_t entrysize_align = memapi_align_bsize(entrysize, sizeof(ringbuffer_entry_st));

    /* new and initialize read and write index by 0 */
    size_t cbLength = RINGBUFST_ALIGN_PAGESIZE(entrysize_align * rblen);
    rbst = (ring_buffer_st *) mem_calloc(1, sizeof(*rbst) + cbLength);
    rbst->Length = cbLength;
    return rbst;
}


void ringbufst_uninit(ringbufst_t rbst)
{
    UAtomicIntSet(&rbst->RLock, 1);
    UAtomicIntSet(&rbst->WLock, 1);
    mem_free(rbst);
}


int ringbufst_write(ringbufst_t rbst, size_t chunksize, void(*write_cb)(uint8_t *, size_t, void *), void *arg)
{
    ringbuffer_entry_st *entry;

    ssize_t Ro, Wo,
        L = (ssize_t) rbst->Length,
        AENTSZ = (ssize_t) RINGBUFST_ALIGN_ENTRYSIZE(chunksize);

    if (! AENTSZ || AENTSZ == RINGBUFST_INVALID_STATE || AENTSZ > (ssize_t) (L / RINGBUFST_ENTRY_HDRSIZE)) {
        assert(0 && "SHOULD NEVER RUN TO THIS!");
        return (-1);
    }

    if (! UAtomicIntCompExch(&rbst->WLock, 0, 1)) {
        /* Get original ROffset */
        Ro = UAtomicIntGet(&rbst->ROffset);
        Wo = rbst->WOffset;

        RINGBUFST_RESTORE_STATE(Ro, Wo, L);

        /* Sw = L - (wrap*L + W - R) */
        if (L - (wrap*L + W - R) >= AENTSZ) {
            if (wrap) { /* wrap(1): 0 .. W < R < L */
                entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[W]);
                entry->size = chunksize;

                write_cb(entry->chunk, entry->size, arg);

                /* WOffset = Wo + AENTSZ */
                W = RINGBUFST_NORMALIZE_OFFSET(Wo + AENTSZ, L);
                UAtomicIntSet(&rbst->WOffset, INT_CAST_TO_ATOMIC(W));
            } else {   /* wrap(0): 0 .. R < W < L */
                if (L - W >= AENTSZ) {
                    entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[W]);
                    entry->size = chunksize;

                    write_cb(entry->chunk, entry->size, arg);

                    /* WOffset = Wo + AENTSZ */
                    W = RINGBUFST_NORMALIZE_OFFSET(Wo + AENTSZ, L);
                    UAtomicIntSet(&rbst->WOffset, INT_CAST_TO_ATOMIC(W));
                } else if (R - 0 >= AENTSZ) {
                    /* clear W slot before wrap W */
                    bzero_fast(&rbst->Buffer[W], L - W);

                    /* wrap W to 0 */
                    entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[0]);
                    entry->size = chunksize;

                    write_cb(entry->chunk, entry->size, arg);

                    /* WOffset = AENTSZ, wrap = 1 */
                    W = AENTSZ + (1 - (int)(Ro/L))*L;

                    UAtomicIntSet(&rbst->WOffset, INT_CAST_TO_ATOMIC(W));
                } else {
                    /* no space left to write. expect to call again(0) */
                    UAtomicIntZero(&rbst->WLock);
                    return 0;
                }
            }

            /* write success */
            UAtomicIntZero(&rbst->WLock);
            return 1;
        }

        /* no space left to write. expect to call again(0) */
        UAtomicIntZero(&rbst->WLock);
        return 0;
    }

    /* lock fail to write, expect to call again(0) */
    return 0;
}


size_t ringbufst_read_copy(ringbufst_t rbst, uint8_t *rdbuf, size_t rdbufsz)
{
    ringbuffer_entry_st *entry;

    ssize_t Ro, Wo, entsize, AENTSZ,
            L = (ssize_t) rbst->Length,
            HENTSZ = (ssize_t)RINGBUFST_ALIGN_ENTRYSIZE(0);

    if (! UAtomicIntCompExch(&rbst->RLock, 0, 1)) {
        Wo = UAtomicIntGet(&rbst->WOffset);
        Ro = rbst->ROffset;

        RINGBUFST_RESTORE_STATE(Ro, Wo, L);

        /* Sr = f*L + W - R */
        if (wrap*L + W - R > HENTSZ) {
            if (wrap) {  /* wrap(1): 0 .. W < R < L */
                if (L - R > HENTSZ) {
                    entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[R]);
                    if (entry->size) {
                        AENTSZ = RINGBUFST_ALIGN_ENTRYSIZE(entry->size);

                        if (L - R >= AENTSZ) {
                            entsize = entry->size;
                            if (entsize > (ssize_t) rdbufsz) {
                                fprintf(stderr, "(ringbufst.c:%d) FATAL: cannot read entry into rdbuf: entsize(%zu) > rdbufsz(%zu)\n",
                                    __LINE__, (size_t) entsize, rdbufsz);
                                fflush(stderr);

                                UAtomicIntZero(&rbst->RLock);
                                return (size_t)entsize;
                            }

                            /* read entry chunk into rdbuf ok */
                            memcpy(rdbuf, entry->chunk, entsize);

                            R = RINGBUFST_NORMALIZE_OFFSET(Ro + AENTSZ, L);
                            UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC(R));

                            /* read success if returned entsize <= rdbufsz */
                            UAtomicIntZero(&rbst->RLock);
                            return (size_t)entsize;
                        }

                        UAtomicIntZero(&rbst->RLock);
                        return (-1);
                    } else {
                        /* reset ROffset to 0 (set wrap = 0) */
                        UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC((Wo/L) * L));

                        /* expect to read again */
                        UAtomicIntZero(&rbst->RLock);
                        return ringbufst_read_copy(rbst, rdbuf, rdbufsz);
                    }
                } else if (W - 0 > HENTSZ) {
                    /* reset ROffset to 0 */
                    entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[0]);
                    if (entry->size) {
                        AENTSZ = RINGBUFST_ALIGN_ENTRYSIZE(entry->size);

                        if (W - 0 >= AENTSZ) {
                            entsize = entry->size;
                            if (entsize > (ssize_t) rdbufsz) {
                                fprintf(stderr, "(ringbufst.c:%d) FATAL: cannot read entry into rdbuf: entsize(%zu) > rdbufsz(%zu)\n",
                                    __LINE__, (size_t) entsize, rdbufsz);
                                fflush(stderr);

                                UAtomicIntZero(&rbst->RLock);
                                return (size_t)entsize;
                            }

                            /* read entry chunk into rdbuf ok */
                            memcpy(rdbuf, entry->chunk, entsize);

                            /* ROffset = AENTSZ, wrap = 0 */
                            UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC(AENTSZ + (Wo/L)*L));

                            /* read success if returned entsize <= rdbufsz */
                            UAtomicIntZero(&rbst->RLock);
                            return (size_t)entsize;
                        }
                    }

                    UAtomicIntZero(&rbst->RLock);
                    return (-1);
                }
            } else {  /* wrap(0): 0 .. R < W < L */
                entry = RINGBUFST_ENTRY_CAST(&rbst->Buffer[R]);
                if (entry->size) {
                    AENTSZ = RINGBUFST_ALIGN_ENTRYSIZE(entry->size);

                    if (W - R >= AENTSZ) {
                        entsize = entry->size;
                        if (entsize > (ssize_t) rdbufsz) {
                            fprintf(stderr, "(ringbufst.c:%d) FATAL: cannot read entry into rdbuf: entsize(%zu) > rdbufsz(%zu)\n",
                                __LINE__, (size_t) entsize, rdbufsz);
                            fflush(stderr);
                            UAtomicIntZero(&rbst->RLock);
                            return (size_t)entsize;
                        }

                        /* read entry chunk into rdbuf ok */
                        memcpy(rdbuf, entry->chunk, entsize);

                        R = RINGBUFST_NORMALIZE_OFFSET(Ro + AENTSZ, L);
                        UAtomicIntSet(&rbst->ROffset, INT_CAST_TO_ATOMIC(R));

                        /* read success if returned entsize <= rdbufsz */
                        UAtomicIntZero(&rbst->RLock);
                        return (size_t) entsize;
                    }
                }

                UAtomicIntZero(&rbst->RLock);
                return (-1);
            }
        }

        /* no entry to read, retry again(0) */
        UAtomicIntZero(&rbst->RLock);
        return 0;
    }

    /* read locked fail, retry again(0) */
    return 0;
}


int ringbufst_read_next(ringbufst_t rbst, int (*nextentry_cb)(const ringbufst_entry entry, void *arg), void *arg)
{
    /* again(0) */
    int ret = 0;

    if (! UAtomicIntCompExch(&rbst->RLock, 0, 1)) {
        ssize_t Wo = UAtomicIntGet(&rbst->WOffset);
        ssize_t Ro = rbst->ROffset;
        ssize_t wrap = RINGBUFST_RESTORE_WRAP(Ro, Wo, rbst->Length);

        ret = ringbufst_read_internal(rbst, wrap, Ro, Wo, (ssize_t)rbst->Length, nextentry_cb, arg);

        UAtomicIntZero(&rbst->RLock);
    }

    return ret;
}


int ringbufst_read_next_batch(ringbufst_t rbst, int (*nextentry_cb)(const ringbufst_entry, void *), void *arg, int batch)
{
    int num = 0, ret = 0;

    if (! UAtomicIntCompExch(&rbst->RLock, 0, 1)) {
        ssize_t wrap, Wo, Ro;

        while (batch-- > 0) {
            Wo = UAtomicIntGet(&rbst->WOffset);
            Ro = rbst->ROffset;
            wrap = RINGBUFST_RESTORE_WRAP(Ro, Wo, rbst->Length);

            ret = ringbufst_read_internal(rbst, wrap, Ro, Wo, (ssize_t)rbst->Length, nextentry_cb, arg);
            if (ret == 1) {
                num++;
                continue;
            }

            if (ret == 0) {
                /* stop current batch */
                break;
            }

            if (ret == -1) {
                num = (-1);
                break;
            }

            assert(0 && "SHOULD NEVER RUN TO THIS!");
        }

        UAtomicIntZero(&rbst->RLock);
    }

    return num;
}
